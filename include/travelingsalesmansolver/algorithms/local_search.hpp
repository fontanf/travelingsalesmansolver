/**
 * Implementation of the Edge Assembly Crossover (EAX) genetic algorithm for
 * the TSP, adapted from Shujia Liu's C++ implementation
 * (https://github.com/Sugia/GA-for-TSP); see 'licenses/eax-ga/NOTICE.md' for
 * the full list of changes made to the original source.
 *
 * All mutable working state lives in 'LocalSearchData'; every operation is a
 * free function taking it (or a 'const&' to it for read-only queries) in
 * place of an implicit 'this', following the same 'LocalSearchData' +
 * free-function pattern as 'local_search_pfss_makespan.cpp'.
 */
namespace
{
/** A TSP tour, represented as a doubly-linked list over its vertices. */
struct Individual
{
    /** Create an individual with no vertices. */
    Individual() { }

    /** Create an individual for a given number of vertices. */
    Individual(VertexId number_of_vertices):
        neighbors(number_of_vertices) { }

    /** Checks if two individuals represent the same tour. */
    bool operator==(
            const Individual& individual) const
    {
        if (neighbors.size() != individual.neighbors.size())
            return false;
        if (length != individual.length)
            return false;

        VertexId current_vertex_id = 0;
        VertexId previous_vertex_id = -1;
        for (std::size_t i = 0; i < neighbors.size(); ++i) {
            VertexId next_vertex_id = (neighbors[current_vertex_id][0] == previous_vertex_id)? neighbors[current_vertex_id][1]: neighbors[current_vertex_id][0];
            if (individual.neighbors[current_vertex_id][0] != next_vertex_id && individual.neighbors[current_vertex_id][1] != next_vertex_id)
                return false;
            previous_vertex_id = current_vertex_id;
            current_vertex_id = next_vertex_id;
        }
        return true;
    }

    /** 'neighbors[vertex_id]' holds the two vertices adjacent to 'vertex_id'. */
    std::vector<std::array<VertexId, 2>> neighbors;

    /** Length of the tour. */
    Distance length = 0;
};

/** Criterion used to choose among the children generated by a crossover. */
enum class EvaluationType
{
    /** Maximize the length improvement. */
    greedy,

    /** Trade the length improvement off against the loss of edge-distance to the population. */
    distance_preservation,

    /** Trade the length improvement off against the loss of edge-frequency entropy. */
    entropy_preservation,
};

/** Strategy used to select the AB-cycles making up an E-set. */
enum class EsetStrategy
{
    /** Each E-set consists of a single AB-cycle. */
    single_ab,

    /** Each E-set consists of an AB-cycle and the ones interacting with it. */
    block2,
};

/**
 * Number of occurrences of each directed edge across the population.
 *
 * Only the edges whose frequency has been modified are stored, in an
 * open-addressing hash table, which requires memory proportional to the number
 * of distinct edges met rather than to the square of the number of vertices.
 */
class EdgeFrequencies
{
public:

    /** Constructor. */
    EdgeFrequencies(VertexId number_of_vertices = 0):
        number_of_vertices_(number_of_vertices),
        entries_(initial_capacity, {-1, 0}) { }

    /** Get the frequency of the edge from 'vertex_id_1' to 'vertex_id_2'. */
    int get(
            VertexId vertex_id_1,
            VertexId vertex_id_2) const
    {
        int64_t key = this->key(vertex_id_1, vertex_id_2);
        for (std::size_t pos = hash(key); ; pos = (pos + 1) & (entries_.size() - 1)) {
            if (entries_[pos].key == key)
                return entries_[pos].frequency;
            if (entries_[pos].key == -1)
                return 0;
        }
    }

    /** Add 'delta' to the frequency of the edge from 'vertex_id_1' to 'vertex_id_2'. */
    void add(
            VertexId vertex_id_1,
            VertexId vertex_id_2,
            int delta)
    {
        int64_t key = this->key(vertex_id_1, vertex_id_2);
        for (std::size_t pos = hash(key); ; pos = (pos + 1) & (entries_.size() - 1)) {
            if (entries_[pos].key == key) {
                entries_[pos].frequency += delta;
                return;
            }
            if (entries_[pos].key == -1) {
                entries_[pos] = {key, delta};
                ++number_of_entries_;
                if (2 * number_of_entries_ > entries_.size())
                    grow();
                return;
            }
        }
    }

    /** Reset all frequencies to 0. */
    void clear()
    {
        std::fill(entries_.begin(), entries_.end(), Entry{-1, 0});
        number_of_entries_ = 0;
    }

private:

    struct Entry
    {
        int64_t key;
        int frequency;

        bool operator==(const Entry& entry) const
        {
            return key == entry.key && frequency == entry.frequency;
        }
    };

    static constexpr std::size_t initial_capacity = 1 << 10;

    int64_t key(
            VertexId vertex_id_1,
            VertexId vertex_id_2) const
    {
        return (int64_t)vertex_id_1 * number_of_vertices_ + vertex_id_2;
    }

    std::size_t hash(int64_t key) const
    {
        return ((uint64_t)key * 0x9E3779B97F4A7C15ull >> 32) & (entries_.size() - 1);
    }

    void grow()
    {
        std::vector<Entry> old_entries(2 * entries_.size(), Entry{-1, 0});
        std::swap(old_entries, entries_);
        for (const Entry& entry: old_entries) {
            if (entry.key == -1)
                continue;
            std::size_t pos = hash(entry.key);
            while (entries_[pos].key != -1)
                pos = (pos + 1) & (entries_.size() - 1);
            entries_[pos] = entry;
        }
    }

    VertexId number_of_vertices_;

    std::vector<Entry> entries_;

    std::size_t number_of_entries_ = 0;

};

/**
 * All mutable working state for the EAX genetic algorithm, shared by every
 * free function below.
 *
 * The fields are grouped by the part of the algorithm using them: instance
 * data, 2-opt local search, crossover, and generation-level state. The vertex
 * neighbor lists are stored in 'near_vertices' (each vertex followed by its
 * 'number_of_near_vertices' nearest neighbors, see 'max_near_vertices').
 */
template <typename Distances>
struct LocalSearchData
{
    /** Constructor: binds 'distances'/'instance'/'parameters'/'output'/'algorithm_formatter' and sizes/computes everything that only depends on 'number_of_vertices'. */
    LocalSearchData(
            const Distances& distances,
            const Instance& instance,
            const LocalSearchParameters& parameters,
            const Output& output,
            AlgorithmFormatter& algorithm_formatter,
            VertexId number_of_vertices);

    ////////////////////////////////////////////////////////////////////////
    // Instance data.
    ////////////////////////////////////////////////////////////////////////

    /** Distances between vertices. */
    const Distances& distances;

    /** Instance, used to build a 'Solution' every time a new best individual is found. */
    const Instance& instance;

    /** Algorithm parameters (used to check 'parameters.timer.needs_to_end()'). */
    const LocalSearchParameters& parameters;

    /** Used to cheaply check whether a candidate individual actually improves on the best solution found so far, before converting it to a 'Solution'. */
    const Output& output;

    /** Used to report every new best individual found, as soon as it is found. */
    AlgorithmFormatter& algorithm_formatter;

    /** Number of vertices. */
    VertexId number_of_vertices;

    /** Random number generator, seeded with 'parameters.seed'. */
    std::mt19937_64 generator;

    /**
     * Number of nearest neighbors stored per vertex (excluding the vertex
     * itself): 'max_near_vertices', or fewer for small instances.
     */
    int number_of_near_vertices;

    /** 'near_vertices[vertex_id][k]' is the k-th nearest vertex to 'vertex_id' ('near_vertices[vertex_id][0] == vertex_id'). */
    std::vector<std::vector<VertexId>> near_vertices;

    ////////////////////////////////////////////////////////////////////////
    // 2-opt local search state.
    ////////////////////////////////////////////////////////////////////////

    /** For each vertex, the vertices in whose nearest-neighbor list it appears. */
    std::vector<std::vector<VertexId>> inverse_near_list;

    /** Number of segments fixed at the start of the current 'optimize()' call. */
    int fixed_number_of_segments = 0;

    /** Current number of segments in the 2-opt tree representation. */
    int number_of_tree_segments = 0;

    /** 'tree_neighbors[vertex_id]' holds the two vertices adjacent to 'vertex_id' within its segment ('-1' at a segment end). */
    std::vector<std::array<VertexId, 2>> tree_neighbors;

    /** 'segment_neighbors[s]' holds the two segments adjacent to segment 's'. */
    std::vector<std::array<int, 2>> segment_neighbors;

    /** 'segment_endpoints[s]' holds the two endpoint vertices of segment 's'. */
    std::vector<std::array<VertexId, 2>> segment_endpoints;

    /** 'vertex_segment[vertex_id]' is the segment 'vertex_id' belongs to. */
    std::vector<int> vertex_segment;

    /** Order of the vertices within their segment, used to tell direction/betweenness cheaply. */
    std::vector<int> vertex_order;

    /** Order of the segments along the tour. */
    std::vector<int> segment_order;

    /** Orientation of each segment (0 or 1). */
    std::vector<int> segment_orientation;

    /** Number of vertices in each segment. */
    std::vector<int> segment_size;

    /** Whether each vertex is still active (a candidate to start a new improving move from). */
    std::vector<int> active;

    /** Scratch array used to build 'individual_to_tree()'. */
    std::vector<VertexId> tree_array;

    /** Scratch array used by 'make_random_solution()'. */
    std::vector<VertexId> remaining;

    ////////////////////////////////////////////////////////////////////////
    // Crossover state.
    ////////////////////////////////////////////////////////////////////////

    /** Population size. */
    int population_size;

    int number_of_unbranched;
    int number_of_branching;

    int number_of_ab_cycles;
    std::vector<VertexId> unbranched;
    std::vector<VertexId> branching;
    std::vector<int> unbranched_index;
    std::vector<int> branching_index;
    std::vector<int> first_visit_position;
    std::vector<VertexId> route;
    std::vector<int> permutation;
    std::vector<VertexId> cycle_buffer;

    /**
     * Per-vertex state used to trace AB-cycles: '[0]' is the number of edges of
     * the vertex not yet traced, '[1]' and '[3]' are its neighbors in parent 1,
     * '[2]' and '[4]' its neighbors in parent 2.
     */
    std::vector<std::vector<VertexId>> parent_neighbors;
    /**
     * The AB-cycles found for the current pair of parents. 'ab_cycle[c][0]' is
     * the length of the cycle, followed by its vertices (with the vertices
     * closing the cycle repeated at both ends).
     */
    std::vector<std::vector<int>> ab_cycle;

    // speeds up start
    int number_of_units;
    /** Number of path segments built while completing a child tour (see 'make_complete_sol()'). */
    int number_of_segments;
    int number_of_segment_positions;
    int number_of_modified_edges;
    int number_of_best_modified_edges;
    int number_of_applied_cycles;
    int number_of_best_applied_cycles;

    std::vector<VertexId> order;
    std::vector<int> inverse_order;
    std::vector<int> segment_unit;
    std::vector<int> segment_position_list;
    std::vector<int> link_a_position;
    std::vector<int> position_segment;
    std::vector<int> number_of_elements_in_unit;
    std::vector<int> center_unit;
    std::vector<VertexId> list_of_center_unit;
    /** Gain in tour length obtained by applying each AB-cycle. */
    std::vector<Distance> ab_cycle_gain;
    std::vector<int> applied_cycle;
    std::vector<int> best_applied_cycle;

    std::vector<std::vector<int>> segment;
    std::vector<std::vector<int>> link_b_position;
    std::vector<std::vector<VertexId>> modified_edge;
    std::vector<std::vector<VertexId>> best_modified_edge;
    // speeds up end

    // block2
    int number_of_used_ab_cycles;
    int number_of_c_nodes;
    int number_of_e_edges;
    int t_max;

    /** "Block2" eset local search stagnation limit (see 'search_eset()'). */
    int eset_max_stagnation;

    int number_of_ab_cycles_in_eset;

    int best_number_of_c_nodes;
    int best_number_of_e_edges;

    std::vector<int> number_of_elements_in_ab_cycle;
    /** For each AB-cycle, the number of vertices it shares with the AB-cycles currently in the E-set. */
    std::vector<int> ab_cycle_overlap_with_eset;

    /** For each AB-cycle, the number of C-nodes (vertices shared with another AB-cycle) it has. */
    std::vector<int> ab_cycle_number_of_c_nodes;
    std::vector<int> used_ab_cycle;
    std::vector<int> moved_ab_cycle;
    std::vector<int> ab_cycle_in_eset;

    /** For each vertex, the (at most two) AB-cycles it belongs to, or -1. */
    std::vector<std::vector<int>> vertex_ab_cycles;

    /**
     * 'ab_cycle_overlap[ab_number]' lists, sorted by increasing AB-cycle number,
     * the other AB-cycles sharing vertices with 'ab_number' along with the
     * number of shared vertices.
     */
    std::vector<std::vector<std::pair<int, int>>> ab_cycle_overlap;

    /** Number of children generated by the last 'run_cross()' call. */
    int number_of_generated_children = 0;

    ////////////////////////////////////////////////////////////////////////
    // Genetic algorithm state.
    ////////////////////////////////////////////////////////////////////////

    /** Number of children generated per generation. */
    int number_of_children;

    /** Current population. */
    std::vector<Individual> population;

    /** Best individual found so far. */
    Individual best_individual;

    /** Number of generations elapsed for the current population. */
    int current_number_of_generations = 0;

    /** Accumulated number of children generated so far. */
    long int accumulated_number_of_children = 0;

    /** Edge frequency across the population. */
    EdgeFrequencies edge_frequency;

    /** Average tour length in the population. */
    double average_value = 0.0;

    /** Tour length of the best individual in the population. */
    Distance best_value = 0;

    /** Random pairing of the population for the current generation's crossovers. */
    std::vector<int> index_for_mating;

    /** Number of consecutive generations without an improvement to 'best_individual'. */
    int stagnation_count = 0;

    /** Criterion used to choose among the children generated by 'run_cross()'. */
    EvaluationType evaluation_type = EvaluationType::entropy_preservation;

    /** Strategy used to select the AB-cycles of the E-sets in 'run_cross()'. */
    EsetStrategy eset_strategy = EsetStrategy::single_ab;

    /** Current stage of the genetic algorithm (1: Single-AB, 2: Block2). */
    int stage = 1;

    /** 'stagnation_count' threshold at which the algorithm moves to the next stage. */
    int max_stagnation = 0;

    /** Number of generations elapsed when stage 1 completed. */
    int number_of_generations_stage_1 = 0;
};

/** Maximum number of nearest neighbors stored per vertex in 'near_vertices'/'inverse_near_list'. */
static constexpr int max_near_vertices = 50;

/** The orientation opposite to 'orientation' (i.e. '1 - orientation'). */
inline int opposite_orientation(
        int orientation)
{
    return 1 - orientation;
}

/** Compute 'near_vertices' from 'data.distances'. */
template <typename Distances>
void compute_near_vertices(
        LocalSearchData<Distances>& data)
{
    if (data.number_of_near_vertices < data.number_of_vertices - 1) {
        // Some vertices are left out of the nearest neighbors lists: use a
        // ball tree.
        BallTree ball_tree(data.instance.distances());
        for (VertexId vertex_id = 0; vertex_id < data.number_of_vertices; ++vertex_id) {
            std::vector<VertexId> neighbor_ids = ball_tree.nearest_neighbors(
                    vertex_id,
                    data.number_of_near_vertices);
            data.near_vertices[vertex_id][0] = vertex_id;
            for (int k = 1; k <= data.number_of_near_vertices; ++k)
                data.near_vertices[vertex_id][k] = neighbor_ids[k - 1];
        }
    } else {
        // All the other vertices are in the nearest neighbors lists: sort them
        // by distance.
        for (VertexId vertex_id = 0; vertex_id < data.number_of_vertices; ++vertex_id) {
            std::vector<VertexId> neighbor_ids;
            for (VertexId other_vertex_id = 0; other_vertex_id < data.number_of_vertices; ++other_vertex_id)
                if (other_vertex_id != vertex_id)
                    neighbor_ids.push_back(other_vertex_id);
            std::sort(
                    neighbor_ids.begin(),
                    neighbor_ids.end(),
                    [&data, vertex_id](VertexId vertex_id_1, VertexId vertex_id_2)
                    {
                        return data.distances.distance(vertex_id, vertex_id_1)
                            < data.distances.distance(vertex_id, vertex_id_2);
                    });
            data.near_vertices[vertex_id][0] = vertex_id;
            for (int k = 1; k <= data.number_of_near_vertices; ++k)
                data.near_vertices[vertex_id][k] = neighbor_ids[k - 1];
        }
    }
}

template <typename Distances>
LocalSearchData<Distances>::LocalSearchData(
        const Distances& distances,
        const Instance& instance,
        const LocalSearchParameters& parameters,
        const Output& output,
        AlgorithmFormatter& algorithm_formatter,
        VertexId number_of_vertices):
    distances(distances),
    instance(instance),
    parameters(parameters),
    output(output),
    algorithm_formatter(algorithm_formatter),
    number_of_vertices(number_of_vertices),
    generator(parameters.seed),
    number_of_near_vertices(std::min<VertexId>(max_near_vertices, number_of_vertices - 1)),
    near_vertices(number_of_vertices, std::vector<VertexId>(number_of_near_vertices + 1)),
    inverse_near_list(number_of_vertices),
    tree_neighbors(number_of_vertices),
    segment_neighbors(number_of_vertices),
    segment_endpoints(number_of_vertices),
    vertex_segment(number_of_vertices),
    vertex_order(number_of_vertices),
    segment_order(number_of_vertices),
    segment_orientation(number_of_vertices),
    segment_size(number_of_vertices),
    active(number_of_vertices),
    tree_array(number_of_vertices + 2),
    remaining(number_of_vertices)
{
    compute_near_vertices(*this);

    for (VertexId vertex_id = 0; vertex_id < number_of_vertices; ++vertex_id) {
        for (int k = 0; k < number_of_near_vertices; ++k) {
            VertexId near_vertex_id = near_vertices[vertex_id][k];
            inverse_near_list[near_vertex_id].push_back(vertex_id);
        }
    }
}

/** Size/fill every field of 'data' that depends on 'population_size'/'number_of_children'. */
template <typename Distances>
void init(
        LocalSearchData<Distances>& data,
        int population_size,
        int number_of_children)
{
    VertexId number_of_vertices = data.number_of_vertices;

    // Crossover state.
    data.population_size = population_size;

    data.parent_neighbors.clear();
    for (int i = 0; i < number_of_vertices; i++) {
        std::vector<VertexId> row(5);
        data.parent_neighbors.push_back(row);
    }

    // Each AB-cycle uses at least 2 distinct red edges, and every vertex is
    // the endpoint of at most 2 of them: there are at most
    // 'number_of_vertices / 2' AB-cycles. The rows of 'ab_cycle' are added as
    // needed by 'form_ab_cycle()'.
    data.ab_cycle.clear();

    data.unbranched.resize(number_of_vertices);
    data.branching.resize(number_of_vertices);
    data.unbranched_index.resize(number_of_vertices);
    data.branching_index.resize(number_of_vertices);
    data.first_visit_position.resize(number_of_vertices);
    data.route.resize(2 * number_of_vertices + 1);
    data.permutation.resize(number_of_vertices);

    data.cycle_buffer.resize(2 * number_of_vertices + 4);

    // speeds up start
    data.order.resize(number_of_vertices);
    data.inverse_order.resize(number_of_vertices);

    // 'number_of_segment_positions'/'number_of_segments' are accumulated across every AB-cycle applied
    // within one crossover call (see 'change_sol()'/'make_unit()'), which in
    // the "Block2" eset mode (multiple AB-cycles per call) can exceed 'number_of_vertices'
    // even though each individual position is a valid index into a tour of
    // 'number_of_vertices' vertices; size these generously (matching 'route'/'cycle_buffer' elsewhere
    // in this file) rather than assuming the count is bounded by 'number_of_vertices'.
    data.segment.clear();
    for (int i = 0; i < 2 * number_of_vertices; i++) {
        std::vector<int> row(2);
        data.segment.push_back(row);
    }

    data.segment_unit.resize(2 * number_of_vertices);
    data.segment_position_list.resize(2 * number_of_vertices);
    data.link_a_position.resize(number_of_vertices);

    data.link_b_position.clear();
    for (int i = 0; i < number_of_vertices; i++) {
        std::vector<int> row(2);
        data.link_b_position.push_back(row);
    }

    data.position_segment.resize(number_of_vertices);
    data.number_of_elements_in_unit.resize(number_of_vertices);

    data.center_unit.resize(number_of_vertices);
    for (int i = 0; i < number_of_vertices; i++) {
        data.center_unit[i] = 0;
    }

    data.list_of_center_unit.resize(number_of_vertices + 2);
    data.ab_cycle_gain.resize(number_of_vertices);

    data.modified_edge.clear();
    for (int i = 0; i < number_of_vertices; i++) {
        std::vector<VertexId> row(4);
        data.modified_edge.push_back(row);
    }

    data.best_modified_edge.clear();
    for (int i = 0; i < number_of_vertices; i++) {
        std::vector<VertexId> row(4);
        data.best_modified_edge.push_back(row);
    }

    data.applied_cycle.resize(number_of_vertices);
    data.best_applied_cycle.resize(number_of_vertices);
    // Speed Up End

    // block2
    data.number_of_elements_in_ab_cycle.resize(number_of_vertices);

    data.vertex_ab_cycles.clear();
    for (int i = 0; i < number_of_vertices; i++) {
        std::vector<int> row(2);
        data.vertex_ab_cycles.push_back(row);
    }

    data.ab_cycle_overlap.assign(number_of_vertices, {});

    data.ab_cycle_overlap_with_eset.resize(number_of_vertices);
    data.ab_cycle_number_of_c_nodes.resize(number_of_vertices);
    data.used_ab_cycle.resize(number_of_vertices);
    data.moved_ab_cycle.resize(number_of_vertices);
    data.ab_cycle_in_eset.resize(number_of_vertices);

    // Genetic algorithm state.
    data.number_of_children = number_of_children;
    data.population = std::vector<Individual>(population_size, Individual(number_of_vertices));
    data.best_individual = Individual(number_of_vertices);
    data.edge_frequency = EdgeFrequencies(number_of_vertices);
    data.index_for_mating.resize(population_size + 1);
}

/** Compute and store the length of an individual's tour. */
template <typename Distances>
void evaluate(
        const LocalSearchData<Distances>& data,
        Individual& individual)
{
    Distance twice_length = 0;
    for (VertexId vertex_id = 0; vertex_id < data.number_of_vertices; ++vertex_id)
        twice_length += data.distances.distance(vertex_id, individual.neighbors[vertex_id][0]) + data.distances.distance(vertex_id, individual.neighbors[vertex_id][1]);
    individual.length = twice_length / 2;
}

/** Build a 'Solution' from the individual's tour. */
template <typename Distances>
Solution to_solution(
        const LocalSearchData<Distances>& data,
        const Individual& individual)
{
    // 'Solution' already starts at vertex 0, so it must not be added again
    // here.
    Solution solution(data.instance);
    VertexId current_vertex_id = 0;
    VertexId start_vertex_id = 0;
    VertexId previous_vertex_id = -1;
    for (int count = 0; count < data.number_of_vertices; ++count) {
        VertexId next_vertex_id = (individual.neighbors[current_vertex_id][0] == previous_vertex_id)?
            individual.neighbors[current_vertex_id][1]:
            individual.neighbors[current_vertex_id][0];
        previous_vertex_id = current_vertex_id;
        current_vertex_id = next_vertex_id;
        if (current_vertex_id == start_vertex_id)
            break;
        solution.add_vertex(data.distances, current_vertex_id);
    }
    return solution;
}

/** Build the tree representation of 'individual'. */
template <typename Distances>
void individual_to_tree(
        LocalSearchData<Distances>& data,
        const Individual& individual)
{
    data.tree_array[1] = 0;
    for (int i = 2; i <= data.number_of_vertices; ++i)
        data.tree_array[i] = individual.neighbors[data.tree_array[i - 1]][1];
    data.tree_array[0] = data.tree_array[data.number_of_vertices];
    data.tree_array[data.number_of_vertices + 1] = data.tree_array[1];

    int position = 1;
    data.number_of_tree_segments = 0;
    while (true) {
        int orientation = 1;
        int size = 0;
        data.segment_orientation[data.number_of_tree_segments] = orientation;
        data.segment_order[data.number_of_tree_segments] = data.number_of_tree_segments;

        data.tree_neighbors[data.tree_array[position]][0] = -1;
        data.tree_neighbors[data.tree_array[position]][1] = data.tree_array[position + 1];
        data.vertex_order[data.tree_array[position]] = size;
        data.vertex_segment[data.tree_array[position]] = data.number_of_tree_segments;
        data.segment_endpoints[data.number_of_tree_segments][opposite_orientation(orientation)] = data.tree_array[position];
        ++position;
        ++size;
        for (int i = 0; i < (int)std::sqrt(data.number_of_vertices * 1.0) - 1; ++i) {
            if (position == data.number_of_vertices)
                break;
            data.tree_neighbors[data.tree_array[position]][0] = data.tree_array[position - 1];
            data.tree_neighbors[data.tree_array[position]][1] = data.tree_array[position + 1];
            data.vertex_order[data.tree_array[position]] = size;
            data.vertex_segment[data.tree_array[position]] = data.number_of_tree_segments;
            ++position;
            ++size;
        }
        if (position == data.number_of_vertices - 1) {
            data.tree_neighbors[data.tree_array[position]][0] = data.tree_array[position - 1];
            data.tree_neighbors[data.tree_array[position]][1] = data.tree_array[position + 1];
            data.vertex_order[data.tree_array[position]] = size;
            data.vertex_segment[data.tree_array[position]] = data.number_of_tree_segments;
            ++position;
            ++size;
        }
        data.tree_neighbors[data.tree_array[position]][0] = data.tree_array[position - 1];
        data.tree_neighbors[data.tree_array[position]][1] = -1;
        data.vertex_order[data.tree_array[position]] = size;
        data.vertex_segment[data.tree_array[position]] = data.number_of_tree_segments;
        data.segment_endpoints[data.number_of_tree_segments][orientation] = data.tree_array[position];
        ++position;
        ++size;
        data.segment_size[data.number_of_tree_segments] = size;
        ++data.number_of_tree_segments;
        if (position == data.number_of_vertices + 1)
            break;
    }
    for (int s = 1; s < data.number_of_tree_segments - 1; ++s) {
        data.segment_neighbors[s][0] = s - 1;
        data.segment_neighbors[s][1] = s + 1;
    }
    data.segment_neighbors[0][0] = data.number_of_tree_segments - 1;
    data.segment_neighbors[0][1] = 1;
    data.segment_neighbors[data.number_of_tree_segments - 1][0] = data.number_of_tree_segments - 2;
    data.segment_neighbors[data.number_of_tree_segments - 1][1] = 0;
    data.fixed_number_of_segments = data.number_of_tree_segments;
}

/** Vertex immediately after 'vertex_id' in the tour. */
template <typename Distances>
VertexId next_vertex(
        const LocalSearchData<Distances>& data,
        VertexId vertex_id)
{
    int segment_id = data.vertex_segment[vertex_id];
    int orientation = data.segment_orientation[segment_id];
    VertexId next_vertex_id = data.tree_neighbors[vertex_id][orientation];
    if (next_vertex_id == -1) {
        segment_id = data.segment_neighbors[segment_id][orientation];
        orientation = opposite_orientation(data.segment_orientation[segment_id]);
        next_vertex_id = data.segment_endpoints[segment_id][orientation];
    }
    return next_vertex_id;
}

/** Vertex immediately before 'vertex_id' in the tour. */
template <typename Distances>
VertexId previous_vertex(
        const LocalSearchData<Distances>& data,
        VertexId vertex_id)
{
    int segment_id = data.vertex_segment[vertex_id];
    int orientation = data.segment_orientation[segment_id];
    VertexId previous_vertex_id = data.tree_neighbors[vertex_id][opposite_orientation(orientation)];
    if (previous_vertex_id == -1) {
        segment_id = data.segment_neighbors[segment_id][opposite_orientation(orientation)];
        orientation = data.segment_orientation[segment_id];
        previous_vertex_id = data.segment_endpoints[segment_id][orientation];
    }
    return previous_vertex_id;
}

/** Rebuild 'individual' from the tree representation. */
template <typename Distances>
void tree_to_individual(
        const LocalSearchData<Distances>& data,
        Individual& individual)
{
    for (VertexId vertex_id = 0; vertex_id < data.number_of_vertices; ++vertex_id) {
        individual.neighbors[vertex_id][0] = previous_vertex(data, vertex_id);
        individual.neighbors[vertex_id][1] = next_vertex(data, vertex_id);
    }
    evaluate(data, individual);
}

/** Merge segment 'segment_2' into segment 'segment_1'. */
template <typename Distances>
void merge_segments(
        LocalSearchData<Distances>& data,
        int segment_1,
        int segment_2)
{
    VertexId moved_start_vertex_id = 0, moved_end_vertex_id = 0;
    int direction = 0, next_order = 0, increment = 0;

    if (data.segment_neighbors[segment_1][data.segment_orientation[segment_1]] == segment_2) {
        data.tree_neighbors[data.segment_endpoints[segment_1][data.segment_orientation[segment_1]]][data.segment_orientation[segment_1]] =
            data.segment_endpoints[segment_2][opposite_orientation(data.segment_orientation[segment_2])];
        data.tree_neighbors[data.segment_endpoints[segment_2][opposite_orientation(data.segment_orientation[segment_2])]][opposite_orientation(data.segment_orientation[segment_2])] =
            data.segment_endpoints[segment_1][data.segment_orientation[segment_1]];
        next_order = data.vertex_order[data.segment_endpoints[segment_1][data.segment_orientation[segment_1]]];

        data.segment_endpoints[segment_1][data.segment_orientation[segment_1]] = data.segment_endpoints[segment_2][data.segment_orientation[segment_2]];
        data.segment_neighbors[segment_1][data.segment_orientation[segment_1]] = data.segment_neighbors[segment_2][data.segment_orientation[segment_2]];
        int segment_id = data.segment_neighbors[segment_2][data.segment_orientation[segment_2]];
        data.segment_neighbors[segment_id][opposite_orientation(data.segment_orientation[segment_id])] = segment_1;

        moved_start_vertex_id = data.segment_endpoints[segment_2][opposite_orientation(data.segment_orientation[segment_2])];
        moved_end_vertex_id = data.segment_endpoints[segment_2][data.segment_orientation[segment_2]];
        direction = data.segment_orientation[segment_2];

        increment = (data.segment_orientation[segment_1] == 1) ? 1 : -1;
    } else if (data.segment_neighbors[segment_1][opposite_orientation(data.segment_orientation[segment_1])] == segment_2) {
        data.tree_neighbors[data.segment_endpoints[segment_1][opposite_orientation(data.segment_orientation[segment_1])]][opposite_orientation(data.segment_orientation[segment_1])] =
            data.segment_endpoints[segment_2][data.segment_orientation[segment_2]];
        data.tree_neighbors[data.segment_endpoints[segment_2][data.segment_orientation[segment_2]]][data.segment_orientation[segment_2]] =
            data.segment_endpoints[segment_1][opposite_orientation(data.segment_orientation[segment_1])];
        next_order = data.vertex_order[data.segment_endpoints[segment_1][opposite_orientation(data.segment_orientation[segment_1])]];

        data.segment_endpoints[segment_1][opposite_orientation(data.segment_orientation[segment_1])] = data.segment_endpoints[segment_2][opposite_orientation(data.segment_orientation[segment_2])];
        data.segment_neighbors[segment_1][opposite_orientation(data.segment_orientation[segment_1])] = data.segment_neighbors[segment_2][opposite_orientation(data.segment_orientation[segment_2])];
        int segment_id = data.segment_neighbors[segment_2][opposite_orientation(data.segment_orientation[segment_2])];
        data.segment_neighbors[segment_id][data.segment_orientation[segment_id]] = segment_1;

        moved_start_vertex_id = data.segment_endpoints[segment_2][data.segment_orientation[segment_2]];
        moved_end_vertex_id = data.segment_endpoints[segment_2][opposite_orientation(data.segment_orientation[segment_2])];
        direction = opposite_orientation(data.segment_orientation[segment_2]);

        increment = (data.segment_orientation[segment_1] == 1) ? -1 : 1;
    }
    VertexId current_vertex_id = moved_start_vertex_id;
    next_order = next_order + increment;
    while (true) {
        data.vertex_segment[current_vertex_id] = segment_1;
        data.vertex_order[current_vertex_id] = next_order;

        VertexId next_vertex_id = data.tree_neighbors[current_vertex_id][direction];
        if (data.segment_orientation[segment_1] != data.segment_orientation[segment_2])
            std::swap(data.tree_neighbors[current_vertex_id][0], data.tree_neighbors[current_vertex_id][1]);

        if (current_vertex_id == moved_end_vertex_id)
            break;
        current_vertex_id = next_vertex_id;
        next_order += increment;
    }
    data.segment_size[segment_1] += data.segment_size[segment_2];
    --data.number_of_tree_segments;
}

/** Apply the 2-opt move found by 'optimize()' to the tree representation. */
template <typename Distances>
void apply_move(
        LocalSearchData<Distances>& data,
        const std::array<VertexId, 5>& t,
        bool reversed)
{
    VertexId path_1_start = t[reversed? 2: 1];
    VertexId path_1_end = t[reversed? 4: 3];
    VertexId path_2_start = t[reversed? 3: 4];
    VertexId path_2_end = t[reversed? 1: 2];

    int segment_path_1_start = data.vertex_segment[path_1_start];
    int segment_order_path_1_start = data.segment_order[segment_path_1_start];
    int orientation_path_1_start = data.segment_orientation[segment_path_1_start];
    int segment_path_1_end = data.vertex_segment[path_1_end];
    int segment_order_path_1_end = data.segment_order[segment_path_1_end];
    int orientation_path_1_end = data.segment_orientation[segment_path_1_end];
    int segment_path_2_start = data.vertex_segment[path_2_start];
    int segment_order_path_2_start = data.segment_order[segment_path_2_start];
    int orientation_path_2_start = data.segment_orientation[segment_path_2_start];
    int segment_path_2_end = data.vertex_segment[path_2_end];
    int segment_order_path_2_end = data.segment_order[segment_path_2_end];
    int orientation_path_2_end = data.segment_orientation[segment_path_2_end];

    //////////////////// Type1 ////////////////////////
    if ((segment_path_1_start == segment_path_1_end) && (segment_path_1_start == segment_path_2_start) && (segment_path_1_start == segment_path_2_end)) {
        if ((data.segment_orientation[segment_path_1_start] == 1 && (data.vertex_order[path_1_start] > data.vertex_order[path_1_end])) ||
            (data.segment_orientation[segment_path_1_start] == 0 && (data.vertex_order[path_1_start] < data.vertex_order[path_1_end]))) {
            std::swap(path_1_start, path_2_start);
            std::swap(path_1_end, path_2_end);
            std::swap(segment_path_1_start, segment_path_2_start);
            std::swap(segment_path_1_end, segment_path_2_end);
            std::swap(segment_order_path_1_start, segment_order_path_2_start);
            std::swap(segment_order_path_1_end, segment_order_path_2_end);
            std::swap(orientation_path_1_start, orientation_path_2_start);
            std::swap(orientation_path_1_end, orientation_path_2_end);
        }
        VertexId current_vertex_id = path_1_start;
        int next_order = data.vertex_order[path_1_end];
        while (true) {
            std::swap(data.tree_neighbors[current_vertex_id][0], data.tree_neighbors[current_vertex_id][1]);
            data.vertex_order[current_vertex_id] = next_order;
            if (current_vertex_id == path_1_end)
                break;
            current_vertex_id = data.tree_neighbors[current_vertex_id][opposite_orientation(orientation_path_1_start)];
            if (orientation_path_1_start == 0)
                ++next_order;
            else
                --next_order;
        }

        data.tree_neighbors[path_2_end][orientation_path_1_start] = path_1_end;
        data.tree_neighbors[path_2_start][opposite_orientation(orientation_path_1_start)] = path_1_start;
        data.tree_neighbors[path_1_start][orientation_path_1_start] = path_2_start;
        data.tree_neighbors[path_1_end][opposite_orientation(orientation_path_1_start)] = path_2_end;

        return;
    }
    //////////////////// Type1 ///////////////////////

    int number_of_segments_path_1 = (segment_order_path_1_end >= segment_order_path_1_start) ?
        segment_order_path_1_end - segment_order_path_1_start + 1 :
        segment_order_path_1_end - segment_order_path_1_start + 1 + data.number_of_tree_segments;
    int number_of_segments_path_2 = (segment_order_path_2_end >= segment_order_path_2_start) ?
        segment_order_path_2_end - segment_order_path_2_start + 1 :
        segment_order_path_2_end - segment_order_path_2_start + 1 + data.number_of_tree_segments;

    if (number_of_segments_path_1 > number_of_segments_path_2) {
        std::swap(number_of_segments_path_1, number_of_segments_path_2);
        std::swap(path_1_start, path_2_start);
        std::swap(path_1_end, path_2_end);
        std::swap(segment_path_1_start, segment_path_2_start);
        std::swap(segment_path_1_end, segment_path_2_end);
        std::swap(segment_order_path_1_start, segment_order_path_2_start);
        std::swap(segment_order_path_1_end, segment_order_path_2_end);
        std::swap(orientation_path_1_start, orientation_path_2_start);
        std::swap(orientation_path_1_end, orientation_path_2_end);
    }
    int path_2_end_is_segment_end = (data.tree_neighbors[path_2_end][orientation_path_2_end] == -1) ? 1 : 0;
    int path_2_start_is_segment_end = (data.tree_neighbors[path_2_start][opposite_orientation(orientation_path_2_start)] == -1) ? 1 : 0;

    int length_of_segment_at_path_1_start = std::abs(data.vertex_order[path_2_end] - data.vertex_order[data.segment_endpoints[segment_path_2_end][orientation_path_2_end]]);
    int length_of_segment_at_path_1_end = std::abs(data.vertex_order[path_2_start] - data.vertex_order[data.segment_endpoints[segment_path_2_start][opposite_orientation(orientation_path_2_start)]]);

    ///////////////////// Type2 /////////////////
    if (segment_path_1_start == segment_path_1_end) {
        if (path_2_end_is_segment_end == 1 && path_2_start_is_segment_end == 1) {
            orientation_path_1_start = opposite_orientation(data.segment_orientation[segment_path_1_start]);
            data.segment_orientation[segment_path_1_start] = orientation_path_1_start;
            data.segment_endpoints[segment_path_1_start][orientation_path_1_start] = path_1_start;
            data.segment_endpoints[segment_path_1_start][opposite_orientation(orientation_path_1_start)] = path_1_end;
            data.segment_neighbors[segment_path_1_start][orientation_path_1_start] = segment_path_2_start;
            data.segment_neighbors[segment_path_1_start][opposite_orientation(orientation_path_1_start)] = segment_path_2_end;
            return;
        }
        if (path_2_end_is_segment_end == 0 && path_2_start_is_segment_end == 1) {
            VertexId current_vertex_id = path_1_end;
            int next_order = data.vertex_order[path_1_start];
            while (true) {
                std::swap(data.tree_neighbors[current_vertex_id][0], data.tree_neighbors[current_vertex_id][1]);
                data.vertex_order[current_vertex_id] = next_order;
                if (current_vertex_id == path_1_start)
                    break;
                current_vertex_id = data.tree_neighbors[current_vertex_id][orientation_path_2_end];
                if (orientation_path_2_end == 0)
                    --next_order;
                else
                    ++next_order;
            }
            data.tree_neighbors[path_2_end][orientation_path_2_end] = path_1_end;
            data.tree_neighbors[path_1_start][orientation_path_2_end] = -1;
            data.tree_neighbors[path_1_end][opposite_orientation(orientation_path_2_end)] = path_2_end;
            data.segment_endpoints[segment_path_2_end][orientation_path_2_end] = path_1_start;
            return;
        }
        if (path_2_end_is_segment_end == 1 && path_2_start_is_segment_end == 0) {
            VertexId current_vertex_id = path_1_start;
            int next_order = data.vertex_order[path_1_end];
            while (true) {
                std::swap(data.tree_neighbors[current_vertex_id][0], data.tree_neighbors[current_vertex_id][1]);
                data.vertex_order[current_vertex_id] = next_order;
                if (current_vertex_id == path_1_end)
                    break;
                current_vertex_id = data.tree_neighbors[current_vertex_id][opposite_orientation(orientation_path_2_start)];
                if (orientation_path_2_start == 0)
                    ++next_order;
                else
                    --next_order;
            }
            data.tree_neighbors[path_2_start][opposite_orientation(orientation_path_2_start)] = path_1_start;
            data.tree_neighbors[path_1_end][opposite_orientation(orientation_path_2_start)] = -1;
            data.tree_neighbors[path_1_start][orientation_path_2_start] = path_2_start;
            data.segment_endpoints[segment_path_2_start][opposite_orientation(orientation_path_2_start)] = path_1_end;
            return;
        }
    }

    ///////////////////// Type3 /////////////////

    if (path_2_end_is_segment_end == 1) {
        data.segment_neighbors[segment_path_1_start][opposite_orientation(orientation_path_1_start)] = segment_path_2_start;
    } else {
        segment_path_1_start = data.number_of_tree_segments++;
        orientation_path_1_start = orientation_path_2_end;
        data.tree_neighbors[path_1_start][opposite_orientation(orientation_path_1_start)] = -1;
        data.tree_neighbors[data.segment_endpoints[segment_path_2_end][orientation_path_2_end]][orientation_path_1_start] = -1;
        data.segment_orientation[segment_path_1_start] = orientation_path_1_start;
        data.segment_size[segment_path_1_start] = length_of_segment_at_path_1_start;
        data.segment_endpoints[segment_path_1_start][opposite_orientation(orientation_path_1_start)] = path_1_start;
        data.segment_endpoints[segment_path_1_start][orientation_path_1_start] = data.segment_endpoints[segment_path_2_end][orientation_path_2_end];
        data.segment_neighbors[segment_path_1_start][opposite_orientation(orientation_path_1_start)] = segment_path_2_start;
        data.segment_neighbors[segment_path_1_start][orientation_path_1_start] = data.segment_neighbors[segment_path_2_end][orientation_path_2_end];
        int segment_id = data.segment_neighbors[segment_path_2_end][orientation_path_2_end];
        data.segment_neighbors[segment_id][opposite_orientation(data.segment_orientation[segment_id])] = segment_path_1_start;
    }

    if (path_2_start_is_segment_end == 1) {
        data.segment_neighbors[segment_path_1_end][orientation_path_1_end] = segment_path_2_end;
    } else {
        segment_path_1_end = data.number_of_tree_segments++;
        orientation_path_1_end = orientation_path_2_start;
        data.tree_neighbors[path_1_end][orientation_path_1_end] = -1;
        data.tree_neighbors[data.segment_endpoints[segment_path_2_start][opposite_orientation(orientation_path_2_start)]][opposite_orientation(orientation_path_1_end)] = -1;
        data.segment_orientation[segment_path_1_end] = orientation_path_1_end;
        data.segment_size[segment_path_1_end] = length_of_segment_at_path_1_end;
        data.segment_endpoints[segment_path_1_end][orientation_path_1_end] = path_1_end;
        data.segment_endpoints[segment_path_1_end][opposite_orientation(orientation_path_1_end)] = data.segment_endpoints[segment_path_2_start][opposite_orientation(orientation_path_2_start)];
        data.segment_neighbors[segment_path_1_end][orientation_path_1_end] = segment_path_2_end;
        data.segment_neighbors[segment_path_1_end][opposite_orientation(orientation_path_1_end)] = data.segment_neighbors[segment_path_2_start][opposite_orientation(orientation_path_2_start)];
        int segment_id = data.segment_neighbors[segment_path_2_start][opposite_orientation(orientation_path_2_start)];
        data.segment_neighbors[segment_id][data.segment_orientation[segment_id]] = segment_path_1_end;
    }

    data.tree_neighbors[path_2_end][orientation_path_2_end] = -1;
    data.segment_size[segment_path_2_end] -= length_of_segment_at_path_1_start;
    data.segment_endpoints[segment_path_2_end][orientation_path_2_end] = path_2_end;
    data.segment_neighbors[segment_path_2_end][orientation_path_2_end] = segment_path_1_end;
    data.tree_neighbors[path_2_start][opposite_orientation(orientation_path_2_start)] = -1;
    data.segment_size[segment_path_2_start] -= length_of_segment_at_path_1_end;
    data.segment_endpoints[segment_path_2_start][opposite_orientation(orientation_path_2_start)] = path_2_start;
    data.segment_neighbors[segment_path_2_start][opposite_orientation(orientation_path_2_start)] = segment_path_1_start;

    {
        int segment_id = segment_path_1_end;
        while (true) {
            data.segment_orientation[segment_id] = opposite_orientation(data.segment_orientation[segment_id]);
            if (segment_id == segment_path_1_start)
                break;
            segment_id = data.segment_neighbors[segment_id][data.segment_orientation[segment_id]];
        }
    }

    if (data.segment_size[segment_path_2_end] < length_of_segment_at_path_1_start) {
        int segment_id = data.segment_neighbors[segment_path_2_end][opposite_orientation(data.segment_orientation[segment_path_2_end])];
        data.segment_neighbors[segment_id][data.segment_orientation[segment_id]] = segment_path_1_start;
        segment_id = data.segment_neighbors[segment_path_2_end][data.segment_orientation[segment_path_2_end]];
        data.segment_neighbors[segment_id][opposite_orientation(data.segment_orientation[segment_id])] = segment_path_1_start;
        segment_id = data.segment_neighbors[segment_path_1_start][opposite_orientation(data.segment_orientation[segment_path_1_start])];
        data.segment_neighbors[segment_id][data.segment_orientation[segment_id]] = segment_path_2_end;
        segment_id = data.segment_neighbors[segment_path_1_start][data.segment_orientation[segment_path_1_start]];
        data.segment_neighbors[segment_id][opposite_orientation(data.segment_orientation[segment_id])] = segment_path_2_end;

        std::swap(data.segment_orientation[segment_path_2_end], data.segment_orientation[segment_path_1_start]);
        std::swap(data.segment_size[segment_path_2_end], data.segment_size[segment_path_1_start]);
        std::swap(data.segment_endpoints[segment_path_2_end][0], data.segment_endpoints[segment_path_1_start][0]);
        std::swap(data.segment_endpoints[segment_path_2_end][1], data.segment_endpoints[segment_path_1_start][1]);
        std::swap(data.segment_neighbors[segment_path_2_end][0], data.segment_neighbors[segment_path_1_start][0]);
        std::swap(data.segment_neighbors[segment_path_2_end][1], data.segment_neighbors[segment_path_1_start][1]);
        std::swap(segment_path_2_end, segment_path_1_start);
    }

    if (data.segment_size[segment_path_2_start] < length_of_segment_at_path_1_end) {
        int segment_id = data.segment_neighbors[segment_path_2_start][opposite_orientation(data.segment_orientation[segment_path_2_start])];
        data.segment_neighbors[segment_id][data.segment_orientation[segment_id]] = segment_path_1_end;
        segment_id = data.segment_neighbors[segment_path_2_start][data.segment_orientation[segment_path_2_start]];
        data.segment_neighbors[segment_id][opposite_orientation(data.segment_orientation[segment_id])] = segment_path_1_end;
        segment_id = data.segment_neighbors[segment_path_1_end][opposite_orientation(data.segment_orientation[segment_path_1_end])];
        data.segment_neighbors[segment_id][data.segment_orientation[segment_id]] = segment_path_2_start;
        segment_id = data.segment_neighbors[segment_path_1_end][data.segment_orientation[segment_path_1_end]];
        data.segment_neighbors[segment_id][opposite_orientation(data.segment_orientation[segment_id])] = segment_path_2_start;

        std::swap(data.segment_orientation[segment_path_2_start], data.segment_orientation[segment_path_1_end]);
        std::swap(data.segment_size[segment_path_2_start], data.segment_size[segment_path_1_end]);
        std::swap(data.segment_endpoints[segment_path_2_start][0], data.segment_endpoints[segment_path_1_end][0]);
        std::swap(data.segment_endpoints[segment_path_2_start][1], data.segment_endpoints[segment_path_1_end][1]);
        std::swap(data.segment_neighbors[segment_path_2_start][0], data.segment_neighbors[segment_path_1_end][0]);
        std::swap(data.segment_neighbors[segment_path_2_start][1], data.segment_neighbors[segment_path_1_end][1]);
        std::swap(segment_path_2_start, segment_path_1_end);
    }

    while (data.number_of_tree_segments > data.fixed_number_of_segments) {
        if (data.segment_size[data.segment_neighbors[data.number_of_tree_segments - 1][0]] <
                data.segment_size[data.segment_neighbors[data.number_of_tree_segments - 1][1]])
            merge_segments(data, data.segment_neighbors[data.number_of_tree_segments - 1][0], data.number_of_tree_segments - 1);
        else
            merge_segments(data, data.segment_neighbors[data.number_of_tree_segments - 1][1], data.number_of_tree_segments - 1);
    }
    int order = 0;
    int segment_id = 0;
    while (true) {
        data.segment_order[segment_id] = order;
        ++order;
        segment_id = data.segment_neighbors[segment_id][data.segment_orientation[segment_id]];
        if (segment_id == 0)
            break;
    }
}

/** Repeatedly apply improving 2-opt moves until none remain. */
template <typename Distances>
void optimize(
        LocalSearchData<Distances>& data)
{
    // The four vertices involved in the move currently being considered.
    std::array<VertexId, 5> t;

    std::fill(data.active.begin(), data.active.end(), 1);
    while (true) {
        // Scan the vertices cyclically, starting from a random one, until a
        // move is applied (in which case the scan restarts from a new random
        // vertex) or all the vertices have been scanned without finding any.
        VertexId t1_start = std::uniform_int_distribution<int>(0, data.number_of_vertices - 1)(data.generator);
        t[1] = t1_start;
        bool move_applied = false;
        while (!move_applied) {
            t[1] = next_vertex(data, t[1]);
            if (data.active[t[1]] != 0) {
                // Look for an improving move, considering both the successor
                // (reversed) and the predecessor (not reversed) of 't[1]'.
                for (bool reversed: {false, true}) {
                    if (move_applied)
                        break;
                    t[2] = (!reversed)?
                        previous_vertex(data, t[1]):
                        next_vertex(data, t[1]);
                    for (int near_index = 1; near_index < data.number_of_near_vertices; ++near_index) {
                        t[4] = data.near_vertices[t[1]][near_index];
                        t[3] = (!reversed)?
                            previous_vertex(data, t[4]):
                            next_vertex(data, t[4]);
                        Distance partial_gain = data.distances.distance(t[1], t[2]) - data.distances.distance(t[1], t[4]);
                        if (partial_gain <= 0)
                            break;
                        Distance gain = partial_gain + data.distances.distance(t[3], t[4]) - data.distances.distance(t[3], t[2]);
                        if (gain > 0) {
                            apply_move(data, t, reversed);
                            for (int a = 1; a <= 4; ++a)
                                for (VertexId near_vertex : data.inverse_near_list[t[a]])
                                    data.active[near_vertex] = 1;
                            move_applied = true;
                            break;
                        }
                    }
                }
                if (!move_applied)
                    data.active[t[1]] = 0;
            }
            if (!move_applied && t[1] == t1_start)
                return;
        }
    }
}

/** Run the local search on 'individual'. */
template <typename Distances>
void run_kopt(
        LocalSearchData<Distances>& data,
        Individual& individual)
{
    individual_to_tree(data, individual);
    optimize(data);
    tree_to_individual(data, individual);
}

/** Set 'individual' to a random tour and run the local search on it. */
template <typename Distances>
void make_random_solution(
        LocalSearchData<Distances>& data,
        Individual& individual)
{
    for (VertexId vertex_id = 0; vertex_id < data.number_of_vertices; ++vertex_id)
        data.remaining[vertex_id] = vertex_id;
    std::vector<VertexId> gene(data.number_of_vertices);
    for (int i = 0; i < data.number_of_vertices; ++i) {
        int remaining_index = std::uniform_int_distribution<int>(0, data.number_of_vertices - i - 1)(data.generator);
        gene[i] = data.remaining[remaining_index];
        data.remaining[remaining_index] = data.remaining[data.number_of_vertices - i - 1];
    }

    for (int j = 1; j < data.number_of_vertices - 1; ++j) {
        individual.neighbors[gene[j]][0] = gene[j - 1];
        individual.neighbors[gene[j]][1] = gene[j + 1];
    }
    individual.neighbors[gene[0]][0] = gene[data.number_of_vertices - 1];
    individual.neighbors[gene[0]][1] = gene[1];
    individual.neighbors[gene[data.number_of_vertices - 1]][0] = gene[data.number_of_vertices - 2];
    individual.neighbors[gene[data.number_of_vertices - 1]][1] = gene[0];

    evaluate(data, individual);
}

/** Record the AB-cycle currently being traced by 'set_ab_cycle()'. */
template <typename Distances>
void form_ab_cycle(
        LocalSearchData<Distances>& data,
        int& position_current,
        int start_appearance_count)
{
    int edge_type = (position_current % 2 == 0)? 1: 2;
    VertexId cycle_start = data.route[position_current];
    int cycle_length = 0;
    data.cycle_buffer[cycle_length] = cycle_start;

    int start_count = 0;
    while (true) {
        ++cycle_length;
        --position_current;
        VertexId visiting_vertex = data.route[position_current];
        if (data.parent_neighbors[visiting_vertex][0] == 2) {
            data.unbranched[data.unbranched_index[visiting_vertex]] = data.unbranched[data.number_of_unbranched - 1];
            data.unbranched_index[data.unbranched[data.number_of_unbranched - 1]] = data.unbranched_index[visiting_vertex];
            --data.number_of_unbranched;
            data.branching[data.number_of_branching] = visiting_vertex;
            data.branching_index[visiting_vertex] = data.number_of_branching;
            ++data.number_of_branching;
        } else if (data.parent_neighbors[visiting_vertex][0] == 1) {
            data.branching[data.branching_index[visiting_vertex]] = data.branching[data.number_of_branching - 1];
            data.branching_index[data.branching[data.number_of_branching - 1]] = data.branching_index[visiting_vertex];
            --data.number_of_branching;
        }

        --data.parent_neighbors[visiting_vertex][0];
        if (visiting_vertex == cycle_start)
            ++start_count;
        if (start_count == start_appearance_count)
            break;
        data.cycle_buffer[cycle_length] = visiting_vertex;
    }

    if (cycle_length == 2)
        return;

    if (data.number_of_ab_cycles == (int)data.ab_cycle.size())
        data.ab_cycle.emplace_back();
    data.ab_cycle[data.number_of_ab_cycles].resize(cycle_length + 4);
    data.ab_cycle[data.number_of_ab_cycles][0] = cycle_length;

    if (edge_type == 2) {
        VertexId saved_vertex_id = data.cycle_buffer[0];
        for (int cycle_position = 0; cycle_position < cycle_length - 1; ++cycle_position)
            data.cycle_buffer[cycle_position] = data.cycle_buffer[cycle_position + 1];
        data.cycle_buffer[cycle_length - 1] = saved_vertex_id;
    }

    for (int cycle_position = 0; cycle_position < cycle_length; ++cycle_position)
        data.ab_cycle[data.number_of_ab_cycles][cycle_position + 2] = data.cycle_buffer[cycle_position];

    data.ab_cycle[data.number_of_ab_cycles][1] = data.cycle_buffer[cycle_length - 1];
    data.ab_cycle[data.number_of_ab_cycles][cycle_length + 2] = data.cycle_buffer[0];
    data.ab_cycle[data.number_of_ab_cycles][cycle_length + 3] = data.cycle_buffer[1];

    data.cycle_buffer[cycle_length] = data.cycle_buffer[0];
    data.cycle_buffer[cycle_length + 1] = data.cycle_buffer[1];
    Distance diff = 0;
    for (int cycle_position = 0; cycle_position < cycle_length / 2; ++cycle_position)
        diff = diff + data.distances.distance(data.cycle_buffer[2 * cycle_position], data.cycle_buffer[1 + 2 * cycle_position]) - data.distances.distance(data.cycle_buffer[1 + 2 * cycle_position], data.cycle_buffer[2 + 2 * cycle_position]);

    data.ab_cycle_gain[data.number_of_ab_cycles] = diff;
    ++data.number_of_ab_cycles;
}

/** Find the AB-cycles of a given pair of parents. */
template <typename Distances>
void set_ab_cycle(
        LocalSearchData<Distances>& data,
        const Individual& parent1,
        const Individual& parent2,
        int number_of_kids)
{
    data.number_of_branching = 0;
    data.number_of_unbranched = 0;
    for (VertexId vertex_id = 0; vertex_id < data.number_of_vertices; ++vertex_id) {
        data.parent_neighbors[vertex_id][1] = parent1.neighbors[vertex_id][0];
        data.parent_neighbors[vertex_id][3] = parent1.neighbors[vertex_id][1];
        data.parent_neighbors[vertex_id][0] = 2;

        data.unbranched[data.number_of_unbranched] = vertex_id;
        data.number_of_unbranched++;

        data.parent_neighbors[vertex_id][2] = parent2.neighbors[vertex_id][0];
        data.parent_neighbors[vertex_id][4] = parent2.neighbors[vertex_id][1];
    }
    for (int i = 0; i < data.number_of_vertices; ++i) {
        data.first_visit_position[i] = -1;
        data.unbranched_index[data.unbranched[i]] = i;
    }
    data.number_of_ab_cycles = 0;

    // State of the trace of the current AB-cycle.
    int start_new_trace = 1;
    int position_current = 0;
    int start_appearance_count = 0;
    int traversal_type = 0;
    VertexId trace_start = -1;
    VertexId trace_current_vertex = -1;
    VertexId trace_previous_vertex = -1;
    while (data.number_of_unbranched != 0) {
        if (start_new_trace == 1) {
            position_current = 0;
            int random_pick = std::uniform_int_distribution<int>(0, data.number_of_unbranched - 1)(data.generator);
            trace_start = data.unbranched[random_pick];
            data.first_visit_position[trace_start] = position_current;
            data.route[position_current] = trace_start;
            trace_current_vertex = trace_start;
            traversal_type = 2;
        } else if (start_new_trace == 0) {
            trace_current_vertex = data.route[position_current];
        }

        int cycle_complete = 0;
        while (cycle_complete == 0) {
            position_current++;
            trace_previous_vertex = trace_current_vertex;
            switch (traversal_type) {
            case 1:
                trace_current_vertex = data.parent_neighbors[trace_previous_vertex][position_current % 2 + 1];
                break;
            case 2: {
                int random_pick = std::uniform_int_distribution<int>(0, 1)(data.generator);
                trace_current_vertex = data.parent_neighbors[trace_previous_vertex][position_current % 2 + 1 + 2 * random_pick];
                if (random_pick == 0)
                    std::swap(data.parent_neighbors[trace_previous_vertex][position_current % 2 + 1], data.parent_neighbors[trace_previous_vertex][position_current % 2 + 3]);
                break;
            }
            case 3:
                trace_current_vertex = data.parent_neighbors[trace_previous_vertex][position_current % 2 + 3];
            }
            data.route[position_current] = trace_current_vertex;
            if (data.parent_neighbors[trace_current_vertex][0] == 2) {
                if (trace_current_vertex == trace_start) {
                    if (data.first_visit_position[trace_start] == 0) {
                        if ((position_current - data.first_visit_position[trace_start]) % 2 == 0) {
                            if (data.parent_neighbors[trace_start][position_current % 2 + 1] == trace_previous_vertex)
                                std::swap(data.parent_neighbors[trace_current_vertex][position_current % 2 + 1], data.parent_neighbors[trace_current_vertex][position_current % 2 + 3]);

                            start_appearance_count = 1;
                            form_ab_cycle(data, position_current, start_appearance_count);
                            if (data.eset_strategy == EsetStrategy::single_ab && data.number_of_ab_cycles == number_of_kids)
                                return;

                            start_new_trace = 0;
                            cycle_complete = 1;
                            traversal_type = 1;
                        } else {
                            std::swap(data.parent_neighbors[trace_current_vertex][position_current % 2 + 1], data.parent_neighbors[trace_current_vertex][position_current % 2 + 3]);
                            traversal_type = 2;
                        }
                        data.first_visit_position[trace_start] = position_current;
                    } else {
                        start_appearance_count = 2;
                        form_ab_cycle(data, position_current, start_appearance_count);
                        if (data.eset_strategy == EsetStrategy::single_ab && data.number_of_ab_cycles == number_of_kids)
                            return;

                        start_new_trace = 1;
                        cycle_complete = 1;
                    }
                } else if (data.first_visit_position[trace_current_vertex] == -1) {
                    data.first_visit_position[trace_current_vertex] = position_current;
                    if (data.parent_neighbors[trace_current_vertex][position_current % 2 + 1] == trace_previous_vertex)
                        std::swap(data.parent_neighbors[trace_current_vertex][position_current % 2 + 1], data.parent_neighbors[trace_current_vertex][position_current % 2 + 3]);
                    traversal_type = 2;
                } else if (data.first_visit_position[trace_current_vertex] > 0) {
                    std::swap(data.parent_neighbors[trace_current_vertex][position_current % 2 + 1], data.parent_neighbors[trace_current_vertex][position_current % 2 + 3]);
                    if ((position_current - data.first_visit_position[trace_current_vertex]) % 2 == 0) {
                        start_appearance_count = 1;
                        form_ab_cycle(data, position_current, start_appearance_count);
                        if (data.eset_strategy == EsetStrategy::single_ab && data.number_of_ab_cycles == number_of_kids)
                            return;

                        start_new_trace = 0;
                        cycle_complete = 1;
                        traversal_type = 1;
                    } else {
                        std::swap(data.parent_neighbors[trace_current_vertex][(position_current + 1) % 2 + 1], data.parent_neighbors[trace_current_vertex][(position_current + 1) % 2 + 3]);
                        traversal_type = 3;
                    }
                }
            } else if (data.parent_neighbors[trace_current_vertex][0] == 1) {
                if (trace_current_vertex == trace_start) {
                    start_appearance_count = 1;
                    form_ab_cycle(data, position_current, start_appearance_count);
                    if (data.eset_strategy == EsetStrategy::single_ab && data.number_of_ab_cycles == number_of_kids)
                        return;
                    start_new_trace = 1;
                    cycle_complete = 1;
                } else {
                    traversal_type = 1;
                }
            }
        }
    }
    while (data.number_of_branching != 0) {
        position_current = 0;
        int random_pick = std::uniform_int_distribution<int>(0, data.number_of_branching - 1)(data.generator);
        trace_start = data.branching[random_pick];
        data.route[position_current] = trace_start;
        trace_current_vertex = trace_start;

        int cycle_complete = 0;
        while (cycle_complete == 0) {
            trace_previous_vertex = trace_current_vertex;
            position_current++;
            trace_current_vertex = data.parent_neighbors[trace_previous_vertex][position_current % 2 + 1];
            data.route[position_current] = trace_current_vertex;
            if (trace_current_vertex == trace_start) {
                start_appearance_count = 1;
                form_ab_cycle(data, position_current, start_appearance_count);
                if (data.eset_strategy == EsetStrategy::single_ab && data.number_of_ab_cycles == number_of_kids)
                    return;

                cycle_complete = 1;
            }
        }
    }
}

/** Block2 eset selection: weight each AB-cycle by its interaction with the others. */
template <typename Distances>
void set_weight(
        LocalSearchData<Distances>& data,
        const Individual& parent1,
        const Individual& parent2)
{
    for (VertexId vertex_id = 0; vertex_id < data.number_of_vertices; ++vertex_id) {
        data.vertex_ab_cycles[vertex_id][0] = -1;
        data.vertex_ab_cycles[vertex_id][1] = -1;
    }

    // Step 1:
    for (int s = 0; s < data.number_of_ab_cycles; ++s) {
        int cycle_length = data.ab_cycle[s][0];
        for (int cycle_position = 0; cycle_position < cycle_length / 2; ++cycle_position) {
            VertexId red_vertex_id_1 = data.ab_cycle[s][2 * cycle_position + 2]; // red edge
            VertexId red_vertex_id_2 = data.ab_cycle[s][2 * cycle_position + 3];

            if (data.vertex_ab_cycles[red_vertex_id_1][0] == -1) {
                data.vertex_ab_cycles[red_vertex_id_1][0] = s;
            } else if (data.vertex_ab_cycles[red_vertex_id_1][1] == -1) {
                data.vertex_ab_cycles[red_vertex_id_1][1] = s;
            }

            if (data.vertex_ab_cycles[red_vertex_id_2][0] == -1) {
                data.vertex_ab_cycles[red_vertex_id_2][0] = s;
            } else if (data.vertex_ab_cycles[red_vertex_id_2][1] == -1) {
                data.vertex_ab_cycles[red_vertex_id_2][1] = s;
            }
        }
    }

    // Step 2:
    for (VertexId vertex_id = 0; vertex_id < data.number_of_vertices; ++vertex_id) {
        if (data.vertex_ab_cycles[vertex_id][0] != -1 && data.vertex_ab_cycles[vertex_id][1] == -1) {
            int ab_number = data.vertex_ab_cycles[vertex_id][0];
            VertexId current_vertex_id = vertex_id;

            VertexId previous_vertex_id = -1;
            if (parent1.neighbors[current_vertex_id][0] != parent2.neighbors[current_vertex_id][0] && parent1.neighbors[current_vertex_id][0] != parent2.neighbors[current_vertex_id][1]) {
                previous_vertex_id = parent1.neighbors[current_vertex_id][0];
            } else if (parent1.neighbors[current_vertex_id][1] != parent2.neighbors[current_vertex_id][0] && parent1.neighbors[current_vertex_id][1] != parent2.neighbors[current_vertex_id][1]) {
                previous_vertex_id = parent1.neighbors[current_vertex_id][1];
            }

            while (true) {
                data.vertex_ab_cycles[current_vertex_id][1] = ab_number;

                VertexId next_vertex_id = -1;
                if (parent1.neighbors[current_vertex_id][0] != previous_vertex_id) {
                    next_vertex_id = parent1.neighbors[current_vertex_id][0];
                } else if (parent1.neighbors[current_vertex_id][1] != previous_vertex_id) {
                    next_vertex_id = parent1.neighbors[current_vertex_id][1];
                }

                if (data.vertex_ab_cycles[next_vertex_id][0] == -1) {
                    data.vertex_ab_cycles[next_vertex_id][0] = ab_number;
                } else if (data.vertex_ab_cycles[next_vertex_id][1] == -1) {
                    data.vertex_ab_cycles[next_vertex_id][1] = ab_number;
                }

                if (data.vertex_ab_cycles[next_vertex_id][1] != -1)
                    break;
                previous_vertex_id = current_vertex_id;
                current_vertex_id = next_vertex_id;
            }
        }
    }

    // Step 3:

    for (int ab_cycle_id = 0; ab_cycle_id < data.number_of_ab_cycles; ++ab_cycle_id) {
        data.ab_cycle_number_of_c_nodes[ab_cycle_id] = 0;
        data.ab_cycle_overlap[ab_cycle_id].clear();
    }

    // Number of vertices shared by each pair of distinct AB-cycles.
    std::vector<std::array<int, 2>> shared_vertices;
    for (VertexId vertex_id = 0; vertex_id < data.number_of_vertices; ++vertex_id) {
        int ab_number_1 = data.vertex_ab_cycles[vertex_id][0];
        int ab_number_2 = data.vertex_ab_cycles[vertex_id][1];
        if (ab_number_1 != -1 && ab_number_2 != -1 && ab_number_1 != ab_number_2) {
            shared_vertices.push_back({ab_number_1, ab_number_2});
            shared_vertices.push_back({ab_number_2, ab_number_1});
        }
        if (ab_number_1 != ab_number_2) {
            ++data.ab_cycle_number_of_c_nodes[ab_number_1];
            ++data.ab_cycle_number_of_c_nodes[ab_number_2];
        }
    }
    std::sort(shared_vertices.begin(), shared_vertices.end());
    for (const std::array<int, 2>& pair: shared_vertices) {
        std::vector<std::pair<int, int>>& weights = data.ab_cycle_overlap[pair[0]];
        if (!weights.empty() && weights.back().first == pair[1]) {
            ++weights.back().second;
        } else {
            weights.push_back({pair[1], 1});
        }
    }
}

/** Prepare AB-cycles for a given pair of parents. */
template <typename Distances>
void set_parents(
        LocalSearchData<Distances>& data,
        const Individual& parent1,
        const Individual& parent2,
        int number_of_kids)
{
    set_ab_cycle(data, parent1, parent2, number_of_kids);

    VertexId start_vertex_id = 0;
    VertexId current_vertex_id = -1;
    VertexId next_vertex_id = start_vertex_id;
    for (int i = 0; i < data.number_of_vertices; ++i) {
        VertexId previous_vertex_id = current_vertex_id;
        current_vertex_id = next_vertex_id;
        if (parent1.neighbors[current_vertex_id][0] != previous_vertex_id) {
            next_vertex_id = parent1.neighbors[current_vertex_id][0];
        } else {
            next_vertex_id = parent1.neighbors[current_vertex_id][1];
        }
        data.order[i] = current_vertex_id;
        data.inverse_order[current_vertex_id] = i;
    }

    if (data.eset_strategy == EsetStrategy::block2) {
        data.t_max = 10;
        data.eset_max_stagnation = 20; // 1:Greedy LS, 20:Tabu Search
        set_weight(data, parent1, parent2);
    }
}

/** Apply (type == 1) or roll back (type == 2) an AB-cycle on 'child'. */
template <typename Distances>
void change_sol(
        LocalSearchData<Distances>& data,
        Individual& child,
        int ab_number,
        int type)
{
    int cycle_length = data.ab_cycle[ab_number][0];
    data.cycle_buffer[0] = data.ab_cycle[ab_number][0];

    if (type == 2) {
        for (int cycle_position = 0; cycle_position < cycle_length + 3; ++cycle_position)
            data.cycle_buffer[cycle_length + 3 - cycle_position] = data.ab_cycle[ab_number][cycle_position + 1];
    } else {
        for (int cycle_position = 1; cycle_position <= cycle_length + 3; ++cycle_position)
            data.cycle_buffer[cycle_position] = data.ab_cycle[ab_number][cycle_position];
    }

    for (int cycle_position = 0; cycle_position < cycle_length / 2; ++cycle_position) {
        VertexId red_vertex_id_1 = data.cycle_buffer[2 + 2 * cycle_position];
        VertexId red_vertex_id_2 = data.cycle_buffer[3 + 2 * cycle_position];
        VertexId blue_vertex_id_1 = data.cycle_buffer[1 + 2 * cycle_position];
        VertexId blue_vertex_id_2 = data.cycle_buffer[4 + 2 * cycle_position];

        if (child.neighbors[red_vertex_id_1][0] == red_vertex_id_2) {
            child.neighbors[red_vertex_id_1][0] = blue_vertex_id_1;
        } else {
            child.neighbors[red_vertex_id_1][1] = blue_vertex_id_1;
        }
        if (child.neighbors[red_vertex_id_2][0] == red_vertex_id_1) {
            child.neighbors[red_vertex_id_2][0] = blue_vertex_id_2;
        } else {
            child.neighbors[red_vertex_id_2][1] = blue_vertex_id_2;
        }

        int red_position_1 = data.inverse_order[red_vertex_id_1];
        int red_position_2 = data.inverse_order[red_vertex_id_2];
        int blue_position_1 = data.inverse_order[blue_vertex_id_1];
        int blue_position_2 = data.inverse_order[blue_vertex_id_2];

        if (red_position_1 == 0 && red_position_2 == data.number_of_vertices - 1) {
            data.segment_position_list[data.number_of_segment_positions++] = red_position_1;
        } else if (red_position_1 == data.number_of_vertices - 1 && red_position_2 == 0) {
            data.segment_position_list[data.number_of_segment_positions++] = red_position_2;
        } else if (red_position_1 < red_position_2) {
            data.segment_position_list[data.number_of_segment_positions++] = red_position_2;
        } else if (red_position_2 < red_position_1) {
            data.segment_position_list[data.number_of_segment_positions++] = red_position_1;
        }

        data.link_b_position[red_position_1][1] = data.link_b_position[red_position_1][0];
        data.link_b_position[red_position_2][1] = data.link_b_position[red_position_2][0];
        data.link_b_position[red_position_1][0] = blue_position_1;
        data.link_b_position[red_position_2][0] = blue_position_2;
    }
}

/**
 * The 5th step of EAX: complete the tour from the remaining path segments.
 *
 * Returns the reduction in tour length (possibly negative) it causes.
 */
template <typename Distances>
Distance make_complete_sol(
        LocalSearchData<Distances>& data,
        Individual& child)
{
    Distance modification_gain = 0;
    while (data.number_of_units != 1) {
        int min_unit_vertex = data.number_of_vertices + 12345;
        int center_unit_index;
        for (int unit_id = 0; unit_id < data.number_of_units; ++unit_id)
            if (data.number_of_elements_in_unit[unit_id] < min_unit_vertex) {
                center_unit_index = unit_id;
                min_unit_vertex = data.number_of_elements_in_unit[unit_id];
            }

        VertexId unit_start = -1;
        for (int s = 0; s < data.number_of_segments; ++s)
            if (data.segment_unit[s] == center_unit_index) {
                int first_position = data.segment[s][0];
                unit_start = data.order[first_position];
            }
        VertexId current_vertex_id = -1;
        VertexId next_vertex_id = unit_start;
        int number_of_elements_in_center_unit = 0;
        while (true) {
            VertexId previous_vertex_id = current_vertex_id;
            current_vertex_id = next_vertex_id;
            data.center_unit[current_vertex_id] = 1;
            data.list_of_center_unit[number_of_elements_in_center_unit] = current_vertex_id;
            ++number_of_elements_in_center_unit;
            if (child.neighbors[current_vertex_id][0] != previous_vertex_id) {
                next_vertex_id = child.neighbors[current_vertex_id][0];
            } else {
                next_vertex_id = child.neighbors[current_vertex_id][1];
            }
            if (next_vertex_id == unit_start)
                break;
        }
        data.list_of_center_unit[number_of_elements_in_center_unit] = data.list_of_center_unit[0];
        data.list_of_center_unit[number_of_elements_in_center_unit + 1] = data.list_of_center_unit[1];

        // Look for the best 2-opt-like move connecting the center unit to
        // another unit: first among the 10 nearest neighbors of each vertex of
        // the center unit, then, if none is found, among the 50 nearest ones.
        Distance max_diff = std::numeric_limits<Distance>::min();
        VertexId best_vertex_id_1 = -1;
        VertexId best_vertex_id_2 = -1;
        VertexId best_vertex_id_3 = -1;
        VertexId best_vertex_id_4 = -1;
        for (int near_search_limit: {10, 50}) {
            for (int s = 1; s <= number_of_elements_in_center_unit; ++s) {
                VertexId vertex_id_1 = data.list_of_center_unit[s];

                for (int near_num = 1; near_num <= std::min(near_search_limit, data.number_of_near_vertices); ++near_num) {
                    VertexId vertex_id_3 = data.near_vertices[vertex_id_1][near_num];
                    if (data.center_unit[vertex_id_3] == 0) {
                        for (int unit_side = 0; unit_side < 2; ++unit_side) {
                            VertexId vertex_id_2 = data.list_of_center_unit[s - 1 + 2 * unit_side];
                            for (int neighbor_side = 0; neighbor_side < 2; ++neighbor_side) {
                                VertexId vertex_id_4 = child.neighbors[vertex_id_3][neighbor_side];
                                Distance diff = data.distances.distance(vertex_id_1, vertex_id_2) + data.distances.distance(vertex_id_3, vertex_id_4) - data.distances.distance(vertex_id_1, vertex_id_3) - data.distances.distance(vertex_id_2, vertex_id_4);
                                if (diff > max_diff) {
                                    best_vertex_id_1 = vertex_id_1;
                                    best_vertex_id_2 = vertex_id_2;
                                    best_vertex_id_3 = vertex_id_3;
                                    best_vertex_id_4 = vertex_id_4;
                                    max_diff = diff;
                                }
                                diff = data.distances.distance(vertex_id_1, vertex_id_2) + data.distances.distance(vertex_id_4, vertex_id_3) -
                                    data.distances.distance(vertex_id_1, vertex_id_4) - data.distances.distance(vertex_id_2, vertex_id_3);
                                if (diff > max_diff) {
                                    best_vertex_id_1 = vertex_id_1;
                                    best_vertex_id_2 = vertex_id_2;
                                    best_vertex_id_3 = vertex_id_4;
                                    best_vertex_id_4 = vertex_id_3;
                                    max_diff = diff;
                                }
                            }
                        }
                    }
                }
            }
            if (best_vertex_id_3 != -1)
                break;
        }

        if (best_vertex_id_3 == -1) {
            int random_center_index = std::uniform_int_distribution<int>(0, number_of_elements_in_center_unit - 2)(data.generator);
            VertexId vertex_id_1 = data.list_of_center_unit[random_center_index];
            VertexId vertex_id_2 = data.list_of_center_unit[random_center_index + 1];
            for (VertexId vertex_id = 0; vertex_id < data.number_of_vertices; ++vertex_id) {
                if (data.center_unit[vertex_id] == 0) {
                    best_vertex_id_1 = vertex_id_1;
                    best_vertex_id_2 = vertex_id_2;
                    best_vertex_id_3 = vertex_id;
                    best_vertex_id_4 = child.neighbors[vertex_id][0];
                    break;
                }
            }
            max_diff = data.distances.distance(best_vertex_id_1, best_vertex_id_2) + data.distances.distance(best_vertex_id_3, best_vertex_id_4) - data.distances.distance(vertex_id_1, best_vertex_id_3) - data.distances.distance(vertex_id_2, best_vertex_id_4);
        }

        if (child.neighbors[best_vertex_id_1][0] == best_vertex_id_2) {
            child.neighbors[best_vertex_id_1][0] = best_vertex_id_3;
        } else {
            child.neighbors[best_vertex_id_1][1] = best_vertex_id_3;
        }
        if (child.neighbors[best_vertex_id_2][0] == best_vertex_id_1) {
            child.neighbors[best_vertex_id_2][0] = best_vertex_id_4;
        } else {
            child.neighbors[best_vertex_id_2][1] = best_vertex_id_4;
        }
        if (child.neighbors[best_vertex_id_3][0] == best_vertex_id_4) {
            child.neighbors[best_vertex_id_3][0] = best_vertex_id_1;
        } else {
            child.neighbors[best_vertex_id_3][1] = best_vertex_id_1;
        }
        if (child.neighbors[best_vertex_id_4][0] == best_vertex_id_3) {
            child.neighbors[best_vertex_id_4][0] = best_vertex_id_2;
        } else {
            child.neighbors[best_vertex_id_4][1] = best_vertex_id_2;
        }

        data.modified_edge[data.number_of_modified_edges][0] = best_vertex_id_1;
        data.modified_edge[data.number_of_modified_edges][1] = best_vertex_id_2;
        data.modified_edge[data.number_of_modified_edges][2] = best_vertex_id_3;
        data.modified_edge[data.number_of_modified_edges][3] = best_vertex_id_4;
        ++data.number_of_modified_edges;

        modification_gain += max_diff;

        int best_position_3 = data.inverse_order[best_vertex_id_3];
        int selected_unit_index = -1;
        for (int s = 0; s < data.number_of_segments; ++s)
            if (data.segment[s][0] <= best_position_3 && best_position_3 <= data.segment[s][1]) {
                selected_unit_index = data.segment_unit[s];
                break;
            }

        for (int s = 0; s < data.number_of_segments; ++s)
            if (data.segment_unit[s] == selected_unit_index)
                data.segment_unit[s] = center_unit_index;

        data.number_of_elements_in_unit[center_unit_index] += data.number_of_elements_in_unit[selected_unit_index];

        for (int s = 0; s < data.number_of_segments; ++s)
            if (data.segment_unit[s] == data.number_of_units - 1)
                data.segment_unit[s] = selected_unit_index;

        data.number_of_elements_in_unit[selected_unit_index] = data.number_of_elements_in_unit[data.number_of_units - 1];
        --data.number_of_units;

        for (int s = 0; s < number_of_elements_in_center_unit; ++s) {
            VertexId vertex_id = data.list_of_center_unit[s];
            data.center_unit[vertex_id] = 0;
        }
    }

    return modification_gain;
}

/** The 5-1th step of EAX: group path segments into units. */
template <typename Distances>
void make_unit(
        LocalSearchData<Distances>& data)
{
    int flag = 1;
    for (int s = 0; s < data.number_of_segment_positions; ++s) {
        if (data.segment_position_list[s] == 0) {
            flag = 0;
            break;
        }
    }
    if (flag == 1) {
        data.segment_position_list[data.number_of_segment_positions++] = 0;
        data.link_b_position[data.number_of_vertices - 1][1]  = data.link_b_position[data.number_of_vertices - 1][0];
        data.link_b_position[0][1] = data.link_b_position[0][0];
        data.link_b_position[data.number_of_vertices - 1][0] = 0;
        data.link_b_position[0][0] = data.number_of_vertices - 1;
    }

    std::sort(
            data.segment_position_list.begin(),
            data.segment_position_list.begin() + data.number_of_segment_positions);
    data.number_of_segments = data.number_of_segment_positions;
    for (int s = 0; s < data.number_of_segments - 1; ++s) {
        data.segment[s][0] = data.segment_position_list[s];
        data.segment[s][1] = data.segment_position_list[s + 1] - 1;
    }

    data.segment[data.number_of_segments - 1][0] = data.segment_position_list[data.number_of_segments - 1];
    data.segment[data.number_of_segments - 1][1] = data.number_of_vertices - 1;

    for (int s = 0; s < data.number_of_segments; ++s) {
        data.link_a_position[data.segment[s][0]] = data.segment[s][1];
        data.link_a_position[data.segment[s][1]] = data.segment[s][0];
        data.position_segment[data.segment[s][0]] = s;
        data.position_segment[data.segment[s][1]] = s;
    }

    for (int s = 0; s < data.number_of_segments; ++s)
        data.segment_unit[s] = -1;
    data.number_of_units = 0;

    while (true) {
        int start_position = -1;
        for (int s = 0; s < data.number_of_segments; ++s) {
            if (data.segment_unit[s] == -1) {
                start_position = data.segment[s][0];
                break;
            }
        }
        if (start_position == -1)
            break;

        int previous_position = -1;
        int position1 = start_position;

        while (1) {
            int segment_number = data.position_segment[position1];
            data.segment_unit[segment_number] = data.number_of_units;

            int position2 = data.link_a_position[position1];
            int next_position = data.link_b_position[position2][0];
            if (position1 == position2)
                if (next_position == previous_position)
                    next_position = data.link_b_position[position2][1];

            if (next_position == start_position) {
                ++data.number_of_units;
                break;
            }

            previous_position = position2;
            position1 = next_position;
        }
    }

    for (int s = 0; s < data.number_of_units; ++s)
        data.number_of_elements_in_unit[s] = 0;

    int unit_number = -1;
    int merged_segment_count = -1;
    for (int s = 0; s < data.number_of_segments; ++s) {
        if (data.segment_unit[s] != unit_number) {
            ++merged_segment_count;
            data.segment[merged_segment_count][0] = data.segment[s][0];
            data.segment[merged_segment_count][1] = data.segment[s][1];
            unit_number = data.segment_unit[s];
            data.segment_unit[merged_segment_count] = unit_number;
            data.number_of_elements_in_unit[unit_number] += data.segment[s][1] - data.segment[s][0] + 1;
        } else {
            data.segment[merged_segment_count][1] = data.segment[s][1];
            data.number_of_elements_in_unit[unit_number] += data.segment[s][1] - data.segment[s][0] + 1;
        }
    }
    data.number_of_segments = merged_segment_count + 1;
}

/** Roll back 'child' to parent 1. */
template <typename Distances>
void back_to_pa1(
        LocalSearchData<Distances>& data,
        Individual& child)
{
    for (int s = data.number_of_modified_edges - 1; s >= 0; --s) {
        VertexId vertex_id_1 = data.modified_edge[s][0];
        VertexId vertex_id_3 = data.modified_edge[s][1];
        VertexId vertex_id_2 = data.modified_edge[s][2];
        VertexId vertex_id_4 = data.modified_edge[s][3];

        if (child.neighbors[vertex_id_1][0] == vertex_id_2) {
            child.neighbors[vertex_id_1][0] = vertex_id_3;
        } else {
            child.neighbors[vertex_id_1][1] = vertex_id_3;
        }
        if (child.neighbors[vertex_id_4][0] == vertex_id_3) {
            child.neighbors[vertex_id_4][0] = vertex_id_2;
        } else {
            child.neighbors[vertex_id_4][1] = vertex_id_2;
        }
        if (child.neighbors[vertex_id_2][0] == vertex_id_1) {
            child.neighbors[vertex_id_2][0] = vertex_id_4;
        } else {
            child.neighbors[vertex_id_2][1] = vertex_id_4;
        }
        if (child.neighbors[vertex_id_3][0] == vertex_id_4) {
            child.neighbors[vertex_id_3][0] = vertex_id_1;
        } else {
            child.neighbors[vertex_id_3][1] = vertex_id_1;
        }
    }

    for (int s = 0; s < data.number_of_applied_cycles; ++s) {
        int ab_cycle_id = data.applied_cycle[s];
        change_sol(data, child, ab_cycle_id, 2);
    }
}

/** Set 'child' to the best child found by the last 'run_cross()' call. */
template <typename Distances>
void go_to_best(
        LocalSearchData<Distances>& data,
        Individual& child)
{
    for (int s = 0; s < data.number_of_best_applied_cycles; ++s) {
        int ab_cycle_id = data.best_applied_cycle[s];
        change_sol(data, child, ab_cycle_id, 1);
    }

    for (int s = 0; s < data.number_of_best_modified_edges; ++s) {
        VertexId vertex_id_1 = data.best_modified_edge[s][0];
        VertexId vertex_id_2 = data.best_modified_edge[s][1];
        VertexId vertex_id_3 = data.best_modified_edge[s][2];
        VertexId vertex_id_4 = data.best_modified_edge[s][3];

        if (child.neighbors[vertex_id_1][0] == vertex_id_2) {
            child.neighbors[vertex_id_1][0] = vertex_id_3;
        } else {
            child.neighbors[vertex_id_1][1] = vertex_id_3;
        }
        if (child.neighbors[vertex_id_2][0] == vertex_id_1) {
            child.neighbors[vertex_id_2][0] = vertex_id_4;
        } else {
            child.neighbors[vertex_id_2][1] = vertex_id_4;
        }
        if (child.neighbors[vertex_id_3][0] == vertex_id_4) {
            child.neighbors[vertex_id_3][0] = vertex_id_1;
        } else {
            child.neighbors[vertex_id_3][1] = vertex_id_1;
        }
        if (child.neighbors[vertex_id_4][0] == vertex_id_3) {
            child.neighbors[vertex_id_4][0] = vertex_id_2;
        } else {
            child.neighbors[vertex_id_4][1] = vertex_id_2;
        }
    }
}

/** Update 'data.edge_frequency' for the best child found by the last 'run_cross()' call. */
template <typename Distances>
void increment_edge_freq(
        LocalSearchData<Distances>& data)
{
    for (int s = 0; s < data.number_of_best_applied_cycles; ++s) {
        int ab_cycle_id = data.best_applied_cycle[s];

        int cycle_length = data.ab_cycle[ab_cycle_id][0];
        data.cycle_buffer[0] = data.ab_cycle[ab_cycle_id][0];

        for (int cycle_position = 1; cycle_position <= cycle_length + 3; ++cycle_position)
            data.cycle_buffer[cycle_position] = data.ab_cycle[ab_cycle_id][cycle_position];

        for (int cycle_position = 0; cycle_position < cycle_length / 2; ++cycle_position) {
            VertexId red_vertex_id_1 = data.cycle_buffer[2 + 2 * cycle_position];
            VertexId red_vertex_id_2 = data.cycle_buffer[3 + 2 * cycle_position];
            VertexId blue_vertex_id_1 = data.cycle_buffer[1 + 2 * cycle_position];
            VertexId blue_vertex_id_2 = data.cycle_buffer[4 + 2 * cycle_position];

            data.edge_frequency.add(red_vertex_id_1, blue_vertex_id_1, 1);
            data.edge_frequency.add(red_vertex_id_1, red_vertex_id_2, -1);
            data.edge_frequency.add(red_vertex_id_2, red_vertex_id_1, -1);
            data.edge_frequency.add(red_vertex_id_2, blue_vertex_id_2, 1);
        }
    }
    for (int s = 0; s < data.number_of_best_modified_edges; ++s) {
        VertexId vertex_id_1 = data.best_modified_edge[s][0];
        VertexId vertex_id_2 = data.best_modified_edge[s][1];
        VertexId vertex_id_3 = data.best_modified_edge[s][2];
        VertexId vertex_id_4 = data.best_modified_edge[s][3];

        data.edge_frequency.add(vertex_id_1, vertex_id_2, -1);
        data.edge_frequency.add(vertex_id_3, vertex_id_4, -1);
        data.edge_frequency.add(vertex_id_1, vertex_id_3, 1);
        data.edge_frequency.add(vertex_id_2, vertex_id_4, 1);
        data.edge_frequency.add(vertex_id_2, vertex_id_1, -1);
        data.edge_frequency.add(vertex_id_4, vertex_id_3, -1);
        data.edge_frequency.add(vertex_id_3, vertex_id_1, 1);
        data.edge_frequency.add(vertex_id_4, vertex_id_2, 1);
    }
}

/** Change in the average tour length implied by preserving 'data.edge_frequency'. */
template <typename Distances>
int calc_adaptive_loss(
        LocalSearchData<Distances>& data)
{
    double loss = 0;
    for (int s = 0; s < data.number_of_applied_cycles; ++s) {
        int ab_cycle_id = data.applied_cycle[s];

        int cycle_length = data.ab_cycle[ab_cycle_id][0];
        data.cycle_buffer[0] = data.ab_cycle[ab_cycle_id][0];

        for (int cycle_position = 1; cycle_position <= cycle_length + 3; ++cycle_position)
            data.cycle_buffer[cycle_position] = data.ab_cycle[ab_cycle_id][cycle_position];

        for (int cycle_position = 0; cycle_position < cycle_length / 2; ++cycle_position) {
            VertexId red_vertex_id_1 = data.cycle_buffer[2 + 2 * cycle_position];
            VertexId red_vertex_id_2 = data.cycle_buffer[3 + 2 * cycle_position];
            VertexId blue_vertex_id_1 = data.cycle_buffer[1 + 2 * cycle_position];
            VertexId blue_vertex_id_2 = data.cycle_buffer[4 + 2 * cycle_position];

            loss -= (data.edge_frequency.get(red_vertex_id_1, red_vertex_id_2) - 1);
            loss -= (data.edge_frequency.get(red_vertex_id_2, red_vertex_id_1) - 1);
            loss += data.edge_frequency.get(red_vertex_id_2, blue_vertex_id_2);
            loss += data.edge_frequency.get(blue_vertex_id_2, red_vertex_id_2);

            data.edge_frequency.add(red_vertex_id_1, red_vertex_id_2, -1);
            data.edge_frequency.add(red_vertex_id_2, red_vertex_id_1, -1);
            data.edge_frequency.add(red_vertex_id_2, blue_vertex_id_2, 1);
            data.edge_frequency.add(blue_vertex_id_2, red_vertex_id_2, 1);
        }
    }
    for (int s = 0; s < data.number_of_modified_edges; ++s) {
        VertexId vertex_id_1 = data.modified_edge[s][0];
        VertexId vertex_id_2 = data.modified_edge[s][1];
        VertexId vertex_id_3 = data.modified_edge[s][2];
        VertexId vertex_id_4 = data.modified_edge[s][3];

        loss -= (data.edge_frequency.get(vertex_id_1, vertex_id_2) - 1);
        loss -= (data.edge_frequency.get(vertex_id_2, vertex_id_1) - 1);
        loss -= (data.edge_frequency.get(vertex_id_3, vertex_id_4) - 1);
        loss -= (data.edge_frequency.get(vertex_id_4, vertex_id_3) - 1);

        loss += data.edge_frequency.get(vertex_id_1, vertex_id_3);
        loss += data.edge_frequency.get(vertex_id_3, vertex_id_1);
        loss += data.edge_frequency.get(vertex_id_2, vertex_id_4);
        loss += data.edge_frequency.get(vertex_id_4, vertex_id_2);

        data.edge_frequency.add(vertex_id_1, vertex_id_2, -1);
        data.edge_frequency.add(vertex_id_2, vertex_id_1, -1);
        data.edge_frequency.add(vertex_id_3, vertex_id_4, -1);
        data.edge_frequency.add(vertex_id_4, vertex_id_3, -1);

        data.edge_frequency.add(vertex_id_1, vertex_id_3, 1);
        data.edge_frequency.add(vertex_id_3, vertex_id_1, 1);
        data.edge_frequency.add(vertex_id_2, vertex_id_4, 1);
        data.edge_frequency.add(vertex_id_4, vertex_id_2, 1);
    }
    for (int s = 0; s < data.number_of_applied_cycles; ++s) {
        int ab_cycle_id = data.applied_cycle[s];
        int cycle_length = data.ab_cycle[ab_cycle_id][0];
        data.cycle_buffer[0] = data.ab_cycle[ab_cycle_id][0];
        for (int cycle_position = 1; cycle_position <= cycle_length + 3; ++cycle_position)
            data.cycle_buffer[cycle_position] = data.ab_cycle[ab_cycle_id][cycle_position];

        for (int cycle_position = 0; cycle_position < cycle_length / 2; ++cycle_position) {
            VertexId red_vertex_id_1 = data.cycle_buffer[2 + 2 * cycle_position];
            VertexId red_vertex_id_2 = data.cycle_buffer[3 + 2 * cycle_position];
            VertexId blue_vertex_id_1 = data.cycle_buffer[1 + 2 * cycle_position];
            VertexId blue_vertex_id_2 = data.cycle_buffer[4 + 2 * cycle_position];

            data.edge_frequency.add(red_vertex_id_1, red_vertex_id_2, 1);
            data.edge_frequency.add(red_vertex_id_2, red_vertex_id_1, 1);
            data.edge_frequency.add(red_vertex_id_2, blue_vertex_id_2, -1);
            data.edge_frequency.add(blue_vertex_id_2, red_vertex_id_2, -1);
        }
    }
    for (int s = 0; s < data.number_of_modified_edges; ++s) {
        VertexId vertex_id_1 = data.modified_edge[s][0];
        VertexId vertex_id_2 = data.modified_edge[s][1];
        VertexId vertex_id_3 = data.modified_edge[s][2];
        VertexId vertex_id_4 = data.modified_edge[s][3];

        data.edge_frequency.add(vertex_id_1, vertex_id_2, 1);
        data.edge_frequency.add(vertex_id_2, vertex_id_1, 1);
        data.edge_frequency.add(vertex_id_3, vertex_id_4, 1);
        data.edge_frequency.add(vertex_id_4, vertex_id_3, 1);

        data.edge_frequency.add(vertex_id_1, vertex_id_3, -1);
        data.edge_frequency.add(vertex_id_3, vertex_id_1, -1);
        data.edge_frequency.add(vertex_id_2, vertex_id_4, -1);
        data.edge_frequency.add(vertex_id_4, vertex_id_2, -1);
    }
    return int(loss / 2);
}

/** Change in edge-frequency entropy implied by 'data.edge_frequency'. */
template <typename Distances>
double calc_entropy_loss(
        LocalSearchData<Distances>& data)
{
    double loss = 0;  // AB-cycle
    for (int s = 0; s < data.number_of_applied_cycles; ++s) {
        int ab_cycle_id = data.applied_cycle[s];
        int cycle_length = data.ab_cycle[ab_cycle_id][0];
        data.cycle_buffer[0] = data.ab_cycle[ab_cycle_id][0];

        for (int cycle_position = 1; cycle_position <= cycle_length + 3; ++cycle_position)
            data.cycle_buffer[cycle_position] = data.ab_cycle[ab_cycle_id][cycle_position];

        for (int cycle_position = 0; cycle_position < cycle_length / 2; ++cycle_position) {
            VertexId red_vertex_id_1 = data.cycle_buffer[2 + 2 * cycle_position];
            VertexId red_vertex_id_2 = data.cycle_buffer[3 + 2 * cycle_position];
            VertexId blue_vertex_id_1 = data.cycle_buffer[1 + 2 * cycle_position];
            VertexId blue_vertex_id_2 = data.cycle_buffer[4 + 2 * cycle_position];

            double probability_after = (double)(data.edge_frequency.get(red_vertex_id_1, red_vertex_id_2) - 1) / (double)data.population_size;
            double probability_before = (double)(data.edge_frequency.get(red_vertex_id_1, red_vertex_id_2)) / (double)data.population_size;
            if (data.edge_frequency.get(red_vertex_id_1, red_vertex_id_2) - 1 != 0)
                loss -= probability_after * log(probability_after);
            loss += probability_before * log(probability_before);
            data.edge_frequency.add(red_vertex_id_1, red_vertex_id_2, -1);
            data.edge_frequency.add(red_vertex_id_2, red_vertex_id_1, -1);

            probability_after = (double)(data.edge_frequency.get(red_vertex_id_2, blue_vertex_id_2) + 1) / (double)data.population_size;
            probability_before = (double)(data.edge_frequency.get(red_vertex_id_2, blue_vertex_id_2)) / (double)data.population_size;
            loss -= probability_after * log(probability_after);
            if (data.edge_frequency.get(red_vertex_id_2, blue_vertex_id_2) != 0)
                loss += probability_before * log(probability_before);
            data.edge_frequency.add(red_vertex_id_2, blue_vertex_id_2, 1);
            data.edge_frequency.add(blue_vertex_id_2, red_vertex_id_2, 1);
        }
    }

    for (int s = 0; s < data.number_of_modified_edges; ++s) {
        VertexId vertex_id_1 = data.modified_edge[s][0];
        VertexId vertex_id_2 = data.modified_edge[s][1];
        VertexId vertex_id_3 = data.modified_edge[s][2];
        VertexId vertex_id_4 = data.modified_edge[s][3];

        double probability_after = (double)(data.edge_frequency.get(vertex_id_1, vertex_id_2) - 1) / (double)data.population_size;
        double probability_before = (double)(data.edge_frequency.get(vertex_id_1, vertex_id_2)) / (double)data.population_size;
        if (data.edge_frequency.get(vertex_id_1, vertex_id_2) - 1 != 0)
            loss -= probability_after * log(probability_after);
        loss += probability_before * log(probability_before);
        data.edge_frequency.add(vertex_id_1, vertex_id_2, -1);
        data.edge_frequency.add(vertex_id_2, vertex_id_1, -1);

        probability_after = (double)(data.edge_frequency.get(vertex_id_3, vertex_id_4) - 1) / (double)data.population_size;
        probability_before = (double)(data.edge_frequency.get(vertex_id_3, vertex_id_4)) / (double)data.population_size;
        if (data.edge_frequency.get(vertex_id_3, vertex_id_4) - 1 != 0)
            loss -= probability_after * log(probability_after);
        loss += probability_before * log(probability_before);
        data.edge_frequency.add(vertex_id_3, vertex_id_4, -1);
        data.edge_frequency.add(vertex_id_4, vertex_id_3, -1);

        probability_after = (double)(data.edge_frequency.get(vertex_id_1, vertex_id_3) + 1) / (double)data.population_size;
        probability_before = (double)(data.edge_frequency.get(vertex_id_1, vertex_id_3)) / (double)data.population_size;
        loss -= probability_after * log(probability_after);
        if (data.edge_frequency.get(vertex_id_1, vertex_id_3) != 0)
            loss += probability_before * log(probability_before);
        data.edge_frequency.add(vertex_id_1, vertex_id_3, 1);
        data.edge_frequency.add(vertex_id_3, vertex_id_1, 1);

        probability_after = (double)(data.edge_frequency.get(vertex_id_2, vertex_id_4) + 1) / (double)data.population_size;
        probability_before = (double)(data.edge_frequency.get(vertex_id_2, vertex_id_4)) / (double)data.population_size;
        loss -= probability_after * log(probability_after);
        if (data.edge_frequency.get(vertex_id_2, vertex_id_4) != 0)
            loss += probability_before * log(probability_before);
        data.edge_frequency.add(vertex_id_2, vertex_id_4, 1);
        data.edge_frequency.add(vertex_id_4, vertex_id_2, 1);
    }
    loss = -loss;

    // restores data.edge_frequency
    for (int s = 0; s < data.number_of_applied_cycles; ++s) {
        int ab_cycle_id = data.applied_cycle[s];

        int cycle_length = data.ab_cycle[ab_cycle_id][0];
        data.cycle_buffer[0] = data.ab_cycle[ab_cycle_id][0];

        for (int cycle_position = 1; cycle_position <= cycle_length + 3; ++cycle_position)
            data.cycle_buffer[cycle_position] = data.ab_cycle[ab_cycle_id][cycle_position];

        for (int cycle_position = 0; cycle_position < cycle_length / 2; ++cycle_position) {
            VertexId red_vertex_id_1 = data.cycle_buffer[2 + 2 * cycle_position];
            VertexId red_vertex_id_2 = data.cycle_buffer[3 + 2 * cycle_position];
            VertexId blue_vertex_id_1 = data.cycle_buffer[1 + 2 * cycle_position];
            VertexId blue_vertex_id_2 = data.cycle_buffer[4 + 2 * cycle_position];

            data.edge_frequency.add(red_vertex_id_1, red_vertex_id_2, 1);
            data.edge_frequency.add(red_vertex_id_2, red_vertex_id_1, 1);
            data.edge_frequency.add(red_vertex_id_2, blue_vertex_id_2, -1);
            data.edge_frequency.add(blue_vertex_id_2, red_vertex_id_2, -1);
        }
    }
    for (int s = 0; s < data.number_of_modified_edges; ++s) {
        VertexId vertex_id_1 = data.modified_edge[s][0];
        VertexId vertex_id_2 = data.modified_edge[s][1];
        VertexId vertex_id_3 = data.modified_edge[s][2];
        VertexId vertex_id_4 = data.modified_edge[s][3];

        data.edge_frequency.add(vertex_id_1, vertex_id_2, 1);
        data.edge_frequency.add(vertex_id_2, vertex_id_1, 1);
        data.edge_frequency.add(vertex_id_3, vertex_id_4, 1);
        data.edge_frequency.add(vertex_id_4, vertex_id_3, 1);

        data.edge_frequency.add(vertex_id_1, vertex_id_3, -1);
        data.edge_frequency.add(vertex_id_3, vertex_id_1, -1);
        data.edge_frequency.add(vertex_id_2, vertex_id_4, -1);
        data.edge_frequency.add(vertex_id_4, vertex_id_2, -1);
    }
    return loss;
}

/** Add AB-cycle 'num' to the eset being built by 'search_eset()'. */
template <typename Distances>
void add_ab(
        LocalSearchData<Distances>& data,
        int num)
{
    data.number_of_c_nodes += data.ab_cycle_number_of_c_nodes[num] - 2 * data.ab_cycle_overlap_with_eset[num];
    data.number_of_e_edges += data.ab_cycle[num][0] / 2;

    data.used_ab_cycle[num] = 1;
    ++data.number_of_used_ab_cycles;
    for (const std::pair<int, int>& weight: data.ab_cycle_overlap[num])
        data.ab_cycle_overlap_with_eset[weight.first] += weight.second;
}

/** Remove AB-cycle 'num' from the eset being built by 'search_eset()'. */
template <typename Distances>
void delete_ab(
        LocalSearchData<Distances>& data,
        int num)
{
    data.number_of_c_nodes -= data.ab_cycle_number_of_c_nodes[num] - 2 * data.ab_cycle_overlap_with_eset[num];
    data.number_of_e_edges -= data.ab_cycle[num][0] / 2;

    data.used_ab_cycle[num] = 0;
    --data.number_of_used_ab_cycles;
    for (const std::pair<int, int>& weight: data.ab_cycle_overlap[num])
        data.ab_cycle_overlap_with_eset[weight.first] -= weight.second;
}

/** Block2 eset selection: local search over which AB-cycles to include around 'num'. */
template <typename Distances>
void search_eset(
        LocalSearchData<Distances>& data,
        int center_ab)
{
    data.number_of_c_nodes = 0; // Number of C nodes in E-set
    data.number_of_e_edges = 0; // Number of Edges in E-set

    data.number_of_used_ab_cycles = 0;
    for (int ab_cycle_id = 0; ab_cycle_id < data.number_of_ab_cycles; ++ab_cycle_id) {
        data.used_ab_cycle[ab_cycle_id] = 0;
        data.ab_cycle_overlap_with_eset[ab_cycle_id] = 0;
        data.moved_ab_cycle[ab_cycle_id] = 0;
    }

    for (int s = 0; s < data.number_of_ab_cycles_in_eset; ++s) {
        int ab_cycle_id = data.ab_cycle_in_eset[s];
        add_ab(data, ab_cycle_id);
    }
    int best_number_of_c_nodes = data.number_of_c_nodes;
    int best_number_of_e_edges = data.number_of_e_edges;

    int stagnation = 0;
    int iteration = 0;
    while (1) {
        ++iteration;
        int min_delta_weight_non_tabu = 99999999;
        int improving_change = 0;
        int non_tabu_change = 0;
        int selected_ab_cycle = -1;
        int selected_ab_cycle_non_tabu = -1;
        for (int ab_cycle_id = 0; ab_cycle_id < data.number_of_ab_cycles; ++ab_cycle_id) {
            if (data.used_ab_cycle[ab_cycle_id] == 0 && data.ab_cycle_overlap_with_eset[ab_cycle_id] > 0) {
                int delta_weight = data.ab_cycle_number_of_c_nodes[ab_cycle_id] - 2 * data.ab_cycle_overlap_with_eset[ab_cycle_id];
                if (data.number_of_c_nodes + delta_weight < best_number_of_c_nodes) {
                    selected_ab_cycle = ab_cycle_id;
                    improving_change = 1;
                    best_number_of_c_nodes = data.number_of_c_nodes + delta_weight;
                }
                if (delta_weight < min_delta_weight_non_tabu && iteration > data.moved_ab_cycle[ab_cycle_id]) {
                    selected_ab_cycle_non_tabu = ab_cycle_id;
                    non_tabu_change = 1;
                    min_delta_weight_non_tabu = delta_weight;
                }
            } else if (data.used_ab_cycle[ab_cycle_id] == 1 && ab_cycle_id != center_ab) {
                int delta_weight = - data.ab_cycle_number_of_c_nodes[ab_cycle_id] + 2 * data.ab_cycle_overlap_with_eset[ab_cycle_id];
                if (data.number_of_c_nodes + delta_weight < best_number_of_c_nodes) {
                    selected_ab_cycle = ab_cycle_id;
                    improving_change = -1;
                    best_number_of_c_nodes = data.number_of_c_nodes + delta_weight;
                }
                if (delta_weight < min_delta_weight_non_tabu && iteration > data.moved_ab_cycle[ab_cycle_id]) {
                    selected_ab_cycle_non_tabu = ab_cycle_id;
                    non_tabu_change = -1;
                    min_delta_weight_non_tabu = delta_weight;
                }
            }
        }

        if (improving_change != 0) {
            if (improving_change == 1) {
                add_ab(data, selected_ab_cycle);
            } else if (improving_change == -1) {
                delete_ab(data, selected_ab_cycle);
            }

            data.moved_ab_cycle[selected_ab_cycle] = iteration + std::uniform_int_distribution<int>(1, data.t_max)(data.generator);

            best_number_of_e_edges = data.number_of_e_edges;

            data.number_of_ab_cycles_in_eset = 0;
            for (int ab_cycle_id = 0; ab_cycle_id < data.number_of_ab_cycles; ++ab_cycle_id)
                if (data.used_ab_cycle[ab_cycle_id] == 1)
                    data.ab_cycle_in_eset[data.number_of_ab_cycles_in_eset++] = ab_cycle_id;

            stagnation = 0;
        } else if (non_tabu_change != 0) {
            if (non_tabu_change == 1) {
                add_ab(data, selected_ab_cycle_non_tabu);
            } else if (non_tabu_change == -1) {
                delete_ab(data, selected_ab_cycle_non_tabu);
            }
            data.moved_ab_cycle[selected_ab_cycle_non_tabu] = iteration + std::uniform_int_distribution<int>(1, data.t_max)(data.generator);
        }
        if (improving_change == 0)
            ++stagnation;
        if (stagnation == data.eset_max_stagnation)
            break;
    }
}

/** Generate 'number_of_kids' children from 'child'/'parent2' and set 'child' to the best one found. */
template <typename Distances>
void run_cross(
        LocalSearchData<Distances>& data,
        Individual& child,
        Individual& parent2,
        int number_of_kids,
        int flag_p)
{
    int number_of_candidates = std::min(number_of_kids, data.number_of_ab_cycles);

    if (data.eset_strategy == EsetStrategy::single_ab) {
        std::iota(data.permutation.begin(), data.permutation.begin() + data.number_of_ab_cycles, 0);
        std::shuffle(data.permutation.begin(), data.permutation.begin() + data.number_of_ab_cycles, data.generator);
    } else if (data.eset_strategy == EsetStrategy::block2) {
        for (int k = 0; k < data.number_of_ab_cycles; ++k)
            data.number_of_elements_in_ab_cycle[k] = data.ab_cycle[k][0];
        std::iota(data.permutation.begin(), data.permutation.begin() + data.number_of_ab_cycles, 0);
        std::stable_sort(
                data.permutation.begin(),
                data.permutation.begin() + data.number_of_ab_cycles,
                [&data](int ab_cycle_id_1, int ab_cycle_id_2)
                {
                    return data.number_of_elements_in_ab_cycle[ab_cycle_id_1]
                        > data.number_of_elements_in_ab_cycle[ab_cycle_id_2];
                });
    }
    data.number_of_generated_children = 0;
    double best_point = 0.0;
    Distance best_gain = 0;
    bool improved = false;
    for (int cycle_position = 0; cycle_position < number_of_candidates; ++cycle_position) {
        data.number_of_ab_cycles_in_eset = 0;
        if (data.eset_strategy == EsetStrategy::single_ab) {
            int ab_cycle_id = data.permutation[cycle_position];
            data.ab_cycle_in_eset[data.number_of_ab_cycles_in_eset++] = ab_cycle_id;
        } else if (data.eset_strategy == EsetStrategy::block2) {
            int ab_cycle_id = data.permutation[cycle_position];
            int center_ab = ab_cycle_id;
            // Add 'center_ab' and, with probability 1/2 each, the smaller
            // AB-cycles sharing vertices with it, by increasing number.
            bool center_added = false;
            for (const std::pair<int, int>& weight: data.ab_cycle_overlap[center_ab]) {
                int s = weight.first;
                if (!center_added && s > center_ab) {
                    data.ab_cycle_in_eset[data.number_of_ab_cycles_in_eset++] = center_ab;
                    center_added = true;
                }
                if (data.ab_cycle[s][0] < data.ab_cycle[center_ab][0]) {
                    if (std::uniform_int_distribution<int>(0, 1)(data.generator) == 0)
                        data.ab_cycle_in_eset[data.number_of_ab_cycles_in_eset++] = s;
                }
            }
            if (!center_added)
                data.ab_cycle_in_eset[data.number_of_ab_cycles_in_eset++] = center_ab;
            search_eset(data, center_ab);
        }
        data.number_of_segment_positions = 0;
        Distance gain = 0;
        data.number_of_applied_cycles = 0;
        data.number_of_modified_edges = 0;

        data.number_of_applied_cycles = data.number_of_ab_cycles_in_eset;
        for (int k = 0; k < data.number_of_applied_cycles; ++k) {
            data.applied_cycle[k] = data.ab_cycle_in_eset[k];
            int ab_cycle_id = data.applied_cycle[k];
            change_sol(data, child, ab_cycle_id, flag_p);
            gain += data.ab_cycle_gain[ab_cycle_id];
        }

        make_unit(data);
        gain += make_complete_sol(data, child);

        ++data.number_of_generated_children;

        double loss = 1.0; // Greedy
        if (data.evaluation_type == EvaluationType::distance_preservation) {
            loss = calc_adaptive_loss(data);
        } else if (data.evaluation_type == EvaluationType::entropy_preservation) {
            loss = calc_entropy_loss(data);
        }

        if (loss <= 0.0)
            loss = 0.00000001;

        double point = (double)gain / loss;
        child.length = child.length - gain;

        if (best_point < point && child.length != parent2.length) {
            best_point = point;
            best_gain = gain;
            improved = true;

            data.number_of_best_applied_cycles = data.number_of_applied_cycles;
            for (int s = 0; s < data.number_of_best_applied_cycles; ++s)
                data.best_applied_cycle[s] = data.applied_cycle[s];

            data.number_of_best_modified_edges = data.number_of_modified_edges;
            for (int s = 0; s < data.number_of_best_modified_edges; ++s) {
                data.best_modified_edge[s][0] = data.modified_edge[s][0];
                data.best_modified_edge[s][1] = data.modified_edge[s][1];
                data.best_modified_edge[s][2] = data.modified_edge[s][2];
                data.best_modified_edge[s][3] = data.modified_edge[s][3];
            }

        }
        back_to_pa1(data, child);
        child.length = child.length + gain;
    }
    if (improved) {
        go_to_best(data, child);
        child.length = child.length - best_gain;
        increment_edge_freq(data);
    }
}

/** Number of "C nodes" (unmatched half-edges) if only naively combining the used AB-cycles. */
template <typename Distances>
int calc_c_naive(
        LocalSearchData<Distances>& data)
{
    int count_c_nodes = 0;

    for (VertexId vertex_id = 0; vertex_id < data.number_of_vertices; ++vertex_id) {
        if (data.vertex_ab_cycles[vertex_id][0] != -1 && data.vertex_ab_cycles[vertex_id][1] != -1) {
            int tally = 0;
            if (data.used_ab_cycle[data.vertex_ab_cycles[vertex_id][0]] == 1)
                ++tally;
            if (data.used_ab_cycle[data.vertex_ab_cycles[vertex_id][1]] == 1)
                ++tally;
            if (tally == 1)
                ++count_c_nodes;
        }
    }
    return count_c_nodes;
}

/** Reset the generation counters and eset-selection strategy at the start of a run. */
template <typename Distances>
void reset_state(
        LocalSearchData<Distances>& data)
{
    data.accumulated_number_of_children = 0;
    data.current_number_of_generations = 0;
    data.stagnation_count = 0;
    data.max_stagnation = 0;
    data.stage = 1; // sets stage to 1
    data.evaluation_type = EvaluationType::entropy_preservation; // maintains population diversity
    data.eset_strategy = EsetStrategy::single_ab;
}

/** Whether the algorithm should stop (time limit, population convergence, or stagnation). */
template <typename Distances>
bool termination_condition(
        LocalSearchData<Distances>& data)
{
    if (data.parameters.timer.needs_to_end())
        return true;
    if (data.average_value - data.best_value < 0.001)
        return true;
    if (data.stage == 1) {
        if (data.stagnation_count == int(1500 / data.number_of_children) && data.max_stagnation == 0) { // 1500/Nch
            data.max_stagnation = int(data.current_number_of_generations / 10); // data.max_stagnation = G/10
        } else if (data.max_stagnation != 0 && data.max_stagnation <= data.stagnation_count) {
            data.stagnation_count = 0;
            data.max_stagnation = 0;
            data.number_of_generations_stage_1 = data.current_number_of_generations;
            data.eset_strategy = EsetStrategy::block2;
            data.stage = 2;
        }
        return false;
    }
    if (data.stage == 2) {
        if (data.stagnation_count == int(1500 / data.number_of_children) && data.max_stagnation == 0) { // 1500/Nch
            data.max_stagnation = int((data.current_number_of_generations - data.number_of_generations_stage_1) / 10); // data.max_stagnation = G/10
        } else if (data.max_stagnation != 0 && data.max_stagnation <= data.stagnation_count) {
            return true;
        }
        return false;
    }

    return true;
}

/** Update 'average_value'/'best_value'/'best_individual' from the current population. */
template <typename Distances>
void set_average_best(
        LocalSearchData<Distances>& data)
{
    Distance stock_best = data.best_individual.length;
    data.average_value = 0.0;
    int best_index = 0;
    data.best_value = data.population[0].length;
    for (int i = 0; i < data.population_size; ++i) {
        data.average_value += data.population[i].length;
        if (data.population[i].length < data.best_value) {
            best_index = i;
            data.best_value = data.population[i].length;
        }
    }
    data.best_individual = data.population[best_index];
    data.average_value /= (double)data.population_size;
    if (data.best_individual.length < stock_best) {
        data.stagnation_count = 0;
    } else {
        ++data.stagnation_count;
    }
}

/** Set the population to random tours, then locally optimize each of them. */
template <typename Distances>
void init_population(
        LocalSearchData<Distances>& data)
{
    for (int i = 0; i < data.population_size; ++i) {
        // Always build at least the first individual regardless of the time
        // budget, so there is always a solution to report.
        if (i > 0 && data.parameters.timer.needs_to_end())
            break;

        make_random_solution(data, data.population[i]); // randomly sets a data.route
        run_kopt(data, data.population[i]); // local search (2-opt neighborhood)

        if (!data.output.solution.feasible()
                || data.population[i].length < data.output.solution.objective_value()) {
            data.algorithm_formatter.update_solution(
                    to_solution(data, data.population[i]),
                    "individual " + std::to_string(i));
        }
    }
}

/** Draw a random pairing of the population for crossover. */
template <typename Distances>
void select_for_mating(
        LocalSearchData<Distances>& data)
{
    std::iota(data.index_for_mating.begin(), data.index_for_mating.begin() + data.population_size, 0);
    std::shuffle(data.index_for_mating.begin(), data.index_for_mating.begin() + data.population_size, data.generator);
    data.index_for_mating[data.population_size] = data.index_for_mating[0];
}

/** Cross the pair of individuals at 'index_for_mating[s]'/'[s + 1]'. */
template <typename Distances>
void generate_kids(
        LocalSearchData<Distances>& data,
        int s)
{
    // data.population[data.index_for_mating[s]] gets replaced by the best solution found by 'run_cross()'
    // 'data.edge_frequency' gets updated at the same time
    set_parents(data, data.population[data.index_for_mating[s]], data.population[data.index_for_mating[s + 1]], data.number_of_children);
    run_cross(data, data.population[data.index_for_mating[s]], data.population[data.index_for_mating[s + 1]], data.number_of_children, 1);
    data.accumulated_number_of_children += data.number_of_generated_children;
}

/** Recompute 'edge_frequency' from the current population. */
template <typename Distances>
void compute_edge_frequencies(
        LocalSearchData<Distances>& data)
{
    data.edge_frequency.clear();

    for (int i = 0; i < data.population_size; ++i)
        for (VertexId vertex_id = 0; vertex_id < data.number_of_vertices; ++vertex_id) {
            VertexId neighbor_vertex_id_1 = data.population[i].neighbors[vertex_id][0];
            VertexId neighbor_vertex_id_2 = data.population[i].neighbors[vertex_id][1];
            data.edge_frequency.add(vertex_id, neighbor_vertex_id_1, 1);
            data.edge_frequency.add(vertex_id, neighbor_vertex_id_2, 1);
        }
}
}

template <typename Distances>
const Output local_search(
        const Distances& distances,
        const Instance& instance,
        const LocalSearchParameters& parameters)
{
    Output output(instance);
    AlgorithmFormatter algorithm_formatter(parameters, output);
    algorithm_formatter.start("Local Search");
    algorithm_formatter.print_header();

    VertexId number_of_vertices = instance.number_of_vertices();

    LocalSearchData<Distances> data(distances, instance, parameters, output, algorithm_formatter, number_of_vertices);
    init(data, parameters.population_size, parameters.number_of_children);

    init_population(data);

    if (!data.parameters.timer.needs_to_end()) {
        reset_state(data);

        // The genetic algorithm's main loop: maintains a population of
        // individuals, combining pairs of them with 'run_cross()' and locally
        // optimizing the result with 'run_kopt()' each generation.
        compute_edge_frequencies(data);
        while (true) {
            set_average_best(data);
            if (!data.output.solution.feasible()
                    || data.best_individual.length < data.output.solution.objective_value()) {
                data.algorithm_formatter.update_solution(
                        to_solution(data, data.best_individual),
                        "generation " + std::to_string(data.current_number_of_generations));
            }
            if (termination_condition(data))
                break;

            select_for_mating(data);
            for (int s = 0; s < data.population_size; ++s)
                generate_kids(data, s);

            ++data.current_number_of_generations;
        }
    }

    algorithm_formatter.end();
    return output;
}

